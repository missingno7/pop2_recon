"""runtime-symbolic-v1: whole pinned members whose every fixup is proven symbolically.

Uses the immutable original and the pinned MSC 6.00 medium-model library; skipped when
the independent library is not installed.
"""
import copy
import sys
import unittest
from dataclasses import replace
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from common import read_json
import runtime_fixups
from runtime import verify_member

RECIPE = ROOT / "recipes/runtime/crt_dosret_medium.json"
AVAILABLE = RECIPE.exists() and Path(read_json(RECIPE)["library_path"]).exists()


@unittest.skipUnless(AVAILABLE, "pinned MSC 6.00 medium-model library not installed")
class RuntimeSymbolicTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        from oracle import Oracle
        cls.oracle = Oracle.load()
        cls.manifest = read_json(ROOT / "layout/manifest.json")

    def prove(self, name, *, binding=None, manifest=None, oracle=None):
        recipe = read_json(ROOT / f"recipes/runtime/{name}.json")
        binding = binding or read_json(ROOT / recipe["binding"])
        oracle = oracle or self.oracle
        module, overwritten = runtime_fixups.read_member(recipe)
        code = module.segments[recipe["object_segment"]]
        space = oracle.spaces["root"]
        start = space.position(recipe["segment"], recipe["offset"])
        return runtime_fixups.prove(module, overwritten, recipe["object_segment"], code,
                                    space.data[start:start+len(code)], binding, recipe, oracle,
                                    manifest or self.manifest)

    def test_accepts_member_with_dgroup_data_and_secondary_storage(self):
        report = verify_member(read_json(RECIPE), self.oracle, self.manifest)
        self.assertTrue(report["exact"])
        self.assertEqual(report["fixups"], 7)
        kinds = {e["kind"] for e in report["equations"]}
        self.assertEqual(kinds, {"near rel16", "DGROUP offset"})
        placed = {(p["segment"], p["placement"], p["length"]) for p in report["data_placements"]}
        # Own 20-byte _DATA and crt0dat's 82-byte _DATA (a zero-owned provider whose
        # DGROUP base word is an overlay-17 relocation generated by its own fixup).
        self.assertEqual(placed, {("_DATA", 0x22d4, 20), ("_DATA", 0x2274, 82)})
        provider = next(p for p in report["data_placements"] if p["length"] == 82)
        self.assertEqual([e["kind"] for e in provider["equations"]], ["DGROUP offset", "DGROUP base"])
        self.assertEqual(provider["relocation_indices"], [84])

    def test_wrong_dgroup_placement_refused(self):
        binding = read_json(ROOT / read_json(RECIPE)["binding"])
        binding["placements"]["_DATA"] += 2
        report = self.prove("crt_dosret_medium", binding=binding)
        self.assertFalse(report["exact"])
        provider = copy.deepcopy(read_json(ROOT / read_json(RECIPE)["binding"]))
        provider["data_providers"][0]["placement"] += 2
        with self.assertRaisesRegex(ValueError, "differs from the original DGROUP bytes"):
            self.prove("crt_dosret_medium", binding=provider)

    def test_missing_provider_refused(self):
        manifest = copy.deepcopy(self.manifest)
        manifest["owners"] = [o for o in manifest["owners"]
                              if o.get("recipe") != "recipes/runtime/crt_dosret_medium.json"]
        with self.assertRaisesRegex(ValueError, "Code provider __dosret0 is missing"):
            self.prove("crt_close_medium", manifest=manifest)
        binding = read_json(ROOT / "evidence/bindings/crt_close_medium.json")
        del binding["code_providers"]
        with self.assertRaisesRegex(ValueError, "Missing pinned code provider for __dosret0"):
            self.prove("crt_close_medium", binding=binding)

    def test_differing_secondary_segment_refused(self):
        space = self.oracle.spaces["overlay-17"]
        at = (0x30f3 - space.link_segment) * 16 + 0x22d4 + 3   # inside dosret's own _DATA
        data = bytearray(space.data)
        data[at] ^= 0xff
        spaces = dict(self.oracle.spaces, **{"overlay-17": replace(space, data=bytes(data))})
        oracle = SimpleNamespace(data=self.oracle.data, spaces=spaces, mz=self.oracle.mz)
        with self.assertRaisesRegex(ValueError, "Placed segment _DATA differs"):
            self.prove("crt_dosret_medium", oracle=oracle)

    def test_unplaced_secondary_storage_refused(self):
        binding = read_json(ROOT / read_json(RECIPE)["binding"])
        del binding["placements"]
        with self.assertRaisesRegex(ValueError, "Unplaced secondary storage _DATA"):
            self.prove("crt_dosret_medium", binding=binding)

    def test_frame_witness_must_reach_pinned_public(self):
        binding = read_json(ROOT / read_json(RECIPE)["binding"])
        binding["code_frame"]["witnesses"][0]["symbol"] = "__dos_close"
        with self.assertRaisesRegex(ValueError, "frame witness"):
            self.prove("crt_dosret_medium", binding=binding)

    def test_far_call_relocations_and_absolute_public(self):
        report = verify_member(read_json(ROOT / "recipes/runtime/crt_fmemmove_medium.json"),
                               self.oracle, self.manifest)
        kinds = [e["kind"] for e in report["equations"]]
        self.assertEqual(kinds.count("absolute public"), 6)
        self.assertEqual(kinds.count("far pointer"), 1)
        self.assertEqual(report["relocations"], 1)

    def test_layout_conflicts_refused(self):
        row = {"member_sha256": "a", "segment": "_DATA", "placement": 16, "length": 4}
        runtime_fixups.check_layout([{"data_placements": [row]}, {"data_placements": [dict(row)]}])
        with self.assertRaisesRegex(ValueError, "two DGROUP offsets"):
            runtime_fixups.check_layout([{"data_placements": [row]},
                                         {"data_placements": [dict(row, placement=18)]}])
        with self.assertRaisesRegex(ValueError, "overlap"):
            runtime_fixups.check_layout([{"data_placements": [row]},
                                         {"data_placements": [dict(row, member_sha256="b", placement=18)]}])


if __name__ == "__main__":
    unittest.main()
