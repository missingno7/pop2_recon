.MODEL MEDIUM
.DATA
EXTRN MESSAGE_DISPLAY_STATE:WORD
EXTRN MOUSE_PIXEL_BUFFER:WORD
EXTRN MOUSE_PIXEL_BUFFER_SEGMENT:WORD
EXTRN FIRST_MOUSE_HANDLE:WORD
EXTRN SECOND_MOUSE_HANDLE:WORD
EXTRN MOUSE_PRESENT:WORD
.CODE
EXTRN UPDATE_MESSAGE_DISPLAY:NEAR
EXTRN RELEASE_BUFFER:NEAR
EXTRN DISPOSE_HANDLE:NEAR
PUBLIC SHUTDOWN_MOUSE_GRAPHICS

SHUTDOWN_MOUSE_GRAPHICS PROC FAR
    cmp MESSAGE_DISPLAY_STATE, 0
    jl release_mouse_storage
    push cs
    call UPDATE_MESSAGE_DISPLAY
release_mouse_storage:
    sub ax, ax
    cwd
    xchg dx, MOUSE_PIXEL_BUFFER_SEGMENT
    xchg ax, MOUSE_PIXEL_BUFFER
    push dx
    push ax
    push cs
    call RELEASE_BUFFER
    push FIRST_MOUSE_HANDLE
    push cs
    call DISPOSE_HANDLE
    push SECOND_MOUSE_HANDLE
    push cs
    call DISPOSE_HANDLE
    mov cx, MOUSE_PRESENT
    jcxz mouse_done
    sub ax, ax
    int 33h
mouse_done:
    retf
SHUTDOWN_MOUSE_GRAPHICS ENDP
END
