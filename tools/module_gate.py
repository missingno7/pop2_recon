"""Same-source group gate: several reviewed functions from one compiled object.

One historical compilation emits one CODE segment holding several publics in
source order. Each *claim* names a reviewed target and the public that starts
it. Every claim must sit at one shared placement (object offset 0 maps to one
original position), and each is judged over its complete extent: from its
public to the next public or the segment end. Publics that are not claimed are
in-place drafts; they own nothing and are reported as debt.

Supported fixups inside a claim include LOC1 self-relative rel16 operands of a
decoded E8/E9/0F 8x (equation `S - (P + 2)` with S the linked destination):
an own-segment branch to an instruction of the same claim; a near CALL (with or
without PUSH CS) to another public of this object; a near CALL to a grounded
`near-code-entry` outside the object. The existing external DGROUP offset16
modes need witnesses outside the whole object. Everything else, including any
original MZ relocation not generated by a proven field, refuses that claim. No
bytes are masked. This proves CODE_EXACT for each claim and
the relative placement of the group; it does not prove the original file
boundary, declarations outside the group, or link placement.

Object-level rules (refusals, not claim failures): every public lies inside
the initialized CODE segment (or, as a data public, inside a placed DGROUP segment;
see _data_publics) and one public starts at offset 0; fixup fields
are disjoint; a near call is proven only inside the original CS window named by
an independently relocated CALL FAR into a claim (for overlay claims: a vector,
a same-overlay call, an unshared cross-space call or far pointer, or bracketing
overlay relocation site frames, see `_frame_evidence`), so
16-bit IP arithmetic and linear placement agree.
"""
