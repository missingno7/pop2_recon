def _rel16_site(rows, at):
    """The decoded instruction whose rel16 operand is the field at `at`.

    Returns (kind, instruction offset, preceded by a decoded PUSH CS): kind is "call" for
    E8, "jmp" for E9 and "jcc" for 0F 80..8F. Matching bytes alone never qualify."""
    by_address = {insn.address: bytes(insn.bytes) for insn in rows}
    near = by_address.get(at - 1, b"")
    if len(near) == 3 and near[0] in (0xe8, 0xe9):
        return ("call" if near[0] == 0xe8 else "jmp"), at - 1, near[0] == 0xe8 and by_address.get(at - 2) == b"\x0e"
    jcc = by_address.get(at - 2, b"")
    if len(jcc) == 4 and jcc[0] == 0x0f and 0x80 <= jcc[1] <= 0x8f:
        return "jcc", at - 2, False
    raise ValueError("Self-relative field is not the rel16 operand of a decoded E8/E9/0F 8x instruction")


def _self_relative(fix, code_name, publics, near_symbols, piece, at, rows, start, end):
    """Classify one LOC1 self-relative rel16 field of a claim (claim-relative `at`).

    Returns (kind, destination, instruction) where kind is "internal" (own CODE segment,
    destination the object offset of an instruction of this claim), "public" (the name of
    a public of this object, called by E8 with or without PUSH CS) or "external" (the name
    of a grounded near-code-entry symbol, called by E8). The destination of an
    own-segment target is the target displacement plus the encoded LEDATA addend, as the
    linker adds the location's contents to `target - (field + 2)`."""
    target, frame = fix["target"], fix["frame"]
    # The value of a self-relative field is a difference of two positions in one frame, so
    # the target-derived frame (MSC F5) and the own CODE segment frame (MASM F0, or F4 the
    # location) give the same 16-bit value. Any other frame is refused.
    require(fix["loc_type"] == 1 and fix["field_width"] == 2 and
            (frame == {"kind": "target_frame", "target": target} or
             (frame.get("kind") == "segment" and frame.get("name") == code_name)),
            "Unsupported self-relative fixup shape")
    kind, insn_at, push_cs = _rel16_site(rows, at)
    addend = struct.unpack_from("<H", piece, at)[0]
    if target.get("kind") == "segment" and target.get("name") == code_name and target.get("method") in (0, 4):
        destination = ((fix["displacement"] or 0) + addend) & 0xFFFF
        if start <= destination < end:
            require(destination - start in {i.address for i in rows},
                    "Self-relative branch target is not an instruction of the claim")
            return "internal", destination, (kind, insn_at, push_cs)
        callee = [name for name, offset in publics.items() if offset == destination]
        require(kind == "call" and callee, "Self-relative own-segment branch leaves its claim")
        return "public", callee[0], (kind, insn_at, push_cs)
    require(target.get("kind") == "external" and target.get("method") == 6 and fix["displacement"] is None,
            "Unsupported self-relative fixup shape")
    require(addend == 0, "Only zero encoded near-call addends are proven")
    # A near CALL, or a tail JMP (E9) to a grounded external near entry: both keep CS.
    require(kind == "call" or (kind == "jmp" and target["name"] in near_symbols and target["name"] not in publics),
            "Only near CALLs (or a tail JMP to an external near entry) may name a near entry")
    if target["name"] in publics:
        return "public", target["name"], (kind, insn_at, push_cs)
    require(target["name"] in near_symbols,
            "Near call target is neither a public of this object nor a grounded near-code entry")
    return "external", target["name"], (kind, insn_at, push_cs)


def _contained(rows, length, proven=()):
    """Control stays inside the claim: direct in-range jumps only, ending in a return or JMP.
    `proven` jumps carry a self-relative fixup whose linked target was proven in the claim."""
    from disasm import _capstone
    cs, xc = _capstone()
    last = None
    for insn in rows:
        if set(insn.groups).intersection((cs.CS_GRP_JUMP,)) and insn.address not in proven:
            require(len(insn.operands) == 1 and insn.operands[0].type == xc.X86_OP_IMM and
                    0 <= insn.operands[0].imm < length,
                    "Jump leaves the claim or is indirect")
        if bytes(insn.bytes) != b"\x90":
            last = insn
    require(last is not None and (set(last.groups).intersection((cs.CS_GRP_RET, cs.CS_GRP_IRET)) or
                                  last.mnemonic == "jmp"),
            "Control can fall through out of the claim")


def _own_segment(fix, code_name):
    """An offset16 field addressing this object's own CODE segment (switch tables, CS: operands)."""
    target, frame = fix["target"], fix["frame"]
    own = {"kind": "segment", "name": code_name}
    return (not fix["self_relative"] and fix["loc_type"] == 1 and fix["field_width"] == 2 and
            {k: target.get(k) for k in ("kind", "name")} == own and
            (frame.get("kind") == "target_frame" or {k: frame.get(k) for k in ("kind", "name")} == own))


def _tables(fields, piece, start):
    """Jump tables: a run of consecutive own-segment words that another own-segment field
    (the `jmp cs:[bx+T]` displacement) points at. `fields` are claim-relative offsets;
    addends are object offsets, so T - start locates the table inside the claim."""
    present = set(fields)
    starts = sorted({struct.unpack_from("<H", piece, at)[0] - start for at in fields} & present)
    runs = []
    for first in starts:
        last = first
        while last + 2 in present:
            last += 2
        runs.append((first, last + 2))
    merged = []
    for lo, hi in sorted(runs):
        if merged and lo < merged[-1][1]:
            merged[-1] = (merged[-1][0], max(hi, merged[-1][1]))
        else:
            merged.append((lo, hi))
    return merged


def _decode(piece, tables):
    """Decode every byte outside the jump tables, each code run from its own start."""
    cs, _ = _capstone()
    engine = cs.Cs(cs.CS_ARCH_X86, cs.CS_MODE_16)
    engine.detail = True
    rows, cursor = [], 0
    for lo, hi in list(tables) + [(len(piece), len(piece))]:
        chunk = piece[cursor:lo]
        part = list(engine.disasm(chunk, cursor))
        require(sum(i.size for i in part) == len(chunk), "Claim code does not decode completely")
        rows += part
        cursor = hi
    return rows


def _check_placements(module, placements, uses, binding, space, oracle):
    """Each placed DGROUP segment must be over-determined: initialized bytes equal the original
    DGROUP bytes at its placement, or (uninitialized) at least two distinct addends agree."""
    if not placements:
        return {}
    # Overlay code runs with the same DS (the startup DGROUP load); it needs the grounded runtime
    # DGROUP paragraph, since its own space does not hold DGROUP.
    require(binding and "frame" in binding and (space.name == "root" or "dgroup_segment" in binding),
            "Placed data needs the DGROUP frame (and dgroup_segment for overlay owners)")
    # The runtime DGROUP paragraph (the C runtime reloads DS with it before main) is
    # grounded by an original relocated word storing it; initialized DGROUP bytes live in
    # whichever space contains that paragraph (the preloaded overlay 17 in this image).
    if "dgroup_segment" in binding:
        from far_binding import _ground_segment
        seg_spec = binding["dgroup_segment"]
        # The paragraph witnesses are startup words in root; no candidate extent to avoid there.
        _ground_segment({"segment": seg_spec["segment"], "witnesses": seg_spec["witnesses"]},
                        {"space": "root", "segment": 0, "offset": 0, "size": 0}, oracle)
        homes = [sp for sp in oracle.spaces.values()
                 if 0 <= (seg_spec["segment"] - sp.link_segment) * 16 < sp.size]
        require(len(homes) == 1, "DGROUP paragraph does not lie in exactly one space")
        home = homes[0]
        dgroup = (seg_spec["segment"] - home.link_segment) * 16
    else:
        home = space
        dgroup = (binding["frame"]["segment"] - space.link_segment) * 16
    report = {}
    for seg in module.segment_defs:
        if seg["name"] not in placements:
            continue
        p = placements[seg["name"]]
        require(type(p) is int and 0 <= p and p + seg["length"] <= 0x10000, "Placement outside DGROUP")
        content = module.segments.get(seg["name"])
        initialized = module.initialized_ranges.get(seg["name"], [])
        if initialized:
            require("dgroup_segment" in binding,
                    "Initialized placed data needs the grounded runtime DGROUP paragraph (dgroup_segment)")
            require(initialized == [(0, seg["length"])] and seg["length"] >= 2,
                    f"Placed segment {seg['name']} must be completely initialized")
            start = dgroup + p
            require(start + seg["length"] <= home.size and home.data[start:start + seg["length"]] == content,
                    f"Placed segment {seg['name']} content differs from the original DGROUP bytes")
            require(not any(start - 1 <= r["image_offset"] < start + seg["length"] for r in home.relocations),
                    f"Placed segment {seg['name']} overlaps original relocated words")
            basis = f"initialized content equals original {home.name}+{start:#x}"
        else:
            require(len(uses.get(seg["name"], set())) >= 2,
                    f"Uninitialized placed segment {seg['name']} needs two distinct proven addends")
            basis = "two or more distinct addends agree"
        report[seg["name"]] = {"placement": p, "length": seg["length"], "basis": basis}
    require(set(report) == set(placements), "Placement for a segment the object does not declare")
    return report


def _code_vectors(oracle):
    """The original RTLink vector records (tu_census decoding, checked against the manager)."""
    from tu_census import overlay_vectors
    overlays = {n: s for n, s in oracle.spaces.items() if s.descriptor and s.descriptor["flags"] == 4}
    return overlay_vectors(oracle, overlays)


def _bracket_frame(space, position):
    """The site frame bracketing `position` in a monotone overlay relocation table, else None."""
    rows = sorted(space.relocations, key=lambda r: r["image_offset"])
    if any(a["segment"] > b["segment"] for a, b in zip(rows, rows[1:])):
        return None
    before = [r for r in rows if r["image_offset"] <= position]
    after = [r for r in rows if r["image_offset"] >= position]
    if before and after and before[-1]["segment"] == after[0]["segment"]:
        return before[-1]["segment"]
    return None


def _other_overlay_frame(oracle, space, segment, offset):
    """A relocated far word segment:offset that lands inside an overlay claim with a frame other
    than the claim's names another overlay's segment when another code overlay holds that link
    address and its own relocation sites bracket that position with exactly `segment`. A far
    word stores its target segment's frame (probe), and the claim's own sites name a different
    frame there, so the linker resolved the reference into the other overlay's segment."""
    for other in oracle.spaces.values():
        if other.name == space.name or not (other.descriptor and other.descriptor["flags"] == 4):
            continue
        position = (segment - other.link_segment) * 16 + offset
        if not 0 <= position < other.size:
            continue
        if _bracket_frame(other, position) == segment:
            return True
        # At the start of a segment before its first relocation: the next record names the
        # word's frame and every earlier record a smaller one (monotone table), so the only
        # segment of that frame there is the one beginning at or before the next record.
        rows = sorted(other.relocations, key=lambda r: r["image_offset"])
        if any(a["segment"] > b["segment"] for a, b in zip(rows, rows[1:])):
            continue
        after = [r for r in rows if r["image_offset"] >= position]
        before = [r for r in rows if r["image_offset"] < position]
        if after and after[0]["segment"] == segment and (not before or before[-1]["segment"] < segment)                 and position >= (segment - other.link_segment) * 16:
            return True
    return False


def _site_frame(target, space, oracle, hull, grouped=False):
    """("evidence"|"refused", row): the CS frame named by the overlay's own relocation sites.

    RTLink 6.10 writes each overlay relocation record as (site offset, site segment), the
    site segment being the frame of the code segment holding the site: the paragraph floor
    of that segment's start, the same frame every relocated far reference into the segment
    stores (probe: evidence/rtlink-probe/site-frames/). Frames therefore never decrease with
    position. If the last record before the claim's end and the first record from its start
    on name one frame F, the segments holding them both have frame F, so every segment
    between them does, and the claim (one original function, one segment) runs with CS F.
    A relocation-free segment between two frames is never covered (the brackets differ).
    Only for a code segment outside every group: a grouped segment's records still name its
    floor while far references use the group frame (probe $$OVLVEC), so a candidate object
    grouping its CODE segment is refused.
    Refused unless the records are monotone, every relocated far word (stored segment plus
    the offset word before it, any space; a decoded vector naming another overlay excepted)
    that lands inside the object uses F, and F's 64K window holds the whole object."""
    if not (space.descriptor and space.descriptor["flags"] == 4):
        return None
    row = {"kind": "overlay site frame", "space": space.name}
    if grouped:
        # Probe: a grouped segment's records name its own floor; calls use the group frame.
        return "refused", dict(row, reason="code segment is a group member; site frame is not its CS")
    rows = sorted(space.relocations, key=lambda r: r["image_offset"])
    start = space.position(target["segment"], target["offset"])
    end = start + target["size"]
    if any(a["segment"] > b["segment"] for a, b in zip(rows, rows[1:])):
        return "refused", dict(row, reason="overlay relocation site frames are not monotone")
    before = [r for r in rows if r["image_offset"] < end]
    after = [r for r in rows if r["image_offset"] >= start]
    if not before or not after or before[-1]["segment"] != after[0]["segment"]:
        return "refused", dict(row, reason="no relocation records of one site frame bracket the claim")
    frame = before[-1]["segment"]
    row.update(frame=frame, bracket_relocation_indices=[before[-1]["index"], after[0]["index"]])
    lo, hi = hull
    base = (frame - space.link_segment) * 16
    if not (base <= lo and hi <= base + 0x10000):
        return "refused", dict(row, reason="site frame window does not hold the whole object")
    # A decoded RTLink vector's jump word enters only the overlay its descriptor index names.
    elsewhere = {v["position"] + 6 for v in _code_vectors(oracle).values() if v["target_space"] != space.name}
    for source in oracle.spaces.values():
        for record in source.relocations:
            at = record["image_offset"]
            if at < 2 or (source.name == "root" and at in elsewhere):
                continue
            segment = record["stored_word"]
            base_f = (segment - space.link_segment) * 16
            if segment == frame or base_f >= hi or base_f + 0x10000 <= lo:
                continue  # same frame, or no offset under this segment can reach the object
            # `mov r16, SEG X` (B8+r imm16): the bytes before the word are an opcode, not an offset,
            # so its offset is unknown; every other relocated word (CALL/JMP FAR operand, `dd`
            # pointer) stores its offset in the word before it.
            # A relocated segment value is the frame of its target's segment (probe), so a segment
            # load of another frame refers to another segment; only a group frame could alias ours,
            # and MSC medium-model code segments are never grouped (a grouping candidate is refused).
            if at >= 1 and 0xb8 <= source.data[at - 1] <= 0xbf:
                continue
            linked = base_f + struct.unpack_from("<H", source.data, at - 2)[0]
            if not lo <= linked < hi:
                continue
            offset = struct.unpack_from("<H", source.data, at - 2)[0]
            if _other_overlay_frame(oracle, space, segment, offset):
                continue  # the linker resolved it into another overlay's segment of frame `segment`
            return "refused", dict(row, reason=f"relocated far word {source.name}+{at - 2:#x} "
                                               f"enters the object with frame {segment:04x}")
    return "evidence", row


def _reached_near_frames(target, space, oracle, hull):
    """Root claims with no relocated far caller: an original near CALL (`E8`, optionally after
    PUSH CS) outside the object whose rel16 lands on the claim entry, reached by recursive
    descent from an entry that an original relocated CALL FAR names with exactly segment F and
    that offset, runs with CS = F (descent and near calls never change CS), so the claim is
    entered with CS = F. The landing is computed in F's window, so wrap is accounted for."""
    from binding import reachable_from_entry
    entry = space.position(target["segment"], target["offset"])
    lo, hi = hull
    data = space.data
    far_entries = set()
    for r in space.relocations:
        at = r["image_offset"] - 3
        if at >= 0 and data[at] == 0x9a:
            off, seg = struct.unpack_from("<HH", data, at + 1)
            far_entries.add((seg, off))
    found = []
    for seg, off in sorted(far_entries):
        base = (seg - space.link_segment) * 16
        if not (base <= entry < base + 0x10000):
            continue
        try:
            reached = reachable_from_entry(oracle, f"{space.name}:{seg:04x}:{off:04x}")
        except ValueError:
            continue
        for at in reached:
            if data[at] not in (0xe8, 0xe9) or (at < hi and lo < at + 3):  # near CALL or JMP keep CS
                continue
            rel = struct.unpack_from("<H", data, at + 1)[0]
            if base + ((at - base + 3 + rel) & 0xFFFF) == entry:
                found.append({"frame": seg, "kind": "reached near CALL", "space": space.name,
                              "image_offset": at, "entry": f"{space.name}:{seg:04x}:{off:04x}"})
        if found:
            break
    return found[:1]


def _frame_evidence(target, space, oracle, hull, grouped=False):
    """(evidence, unusable): independent original far entries naming this claim's CS.

    Root: the segment words of the reviewed, relocated CALL FARs that enter the target
    (unchanged). An overlay claim's code runs only while its overlay is loaded at its
    link address, so a far entry names its CS only if it provably reaches this overlay:
    - an RTLink vector record whose decoded destination (descriptor index -> this
      overlay, segment:offset -> the claim entry) is the claim; the manager loads the
      section and far-jumps with that segment;
    - a reviewed relocated CALL FAR inside the same overlay, relocated by that overlay's
      own table and outside the whole object: its caller is resident, so its own section
      is, and the destination lies in it;
    - a reviewed relocated CALL FAR from another space, only when no other space holds
      that link address (otherwise it may enter another overlay sharing the segment);
    - the overlay's own relocation site frames bracketing the claim (`_site_frame`).
    `hull` is the object's (start, end) in the claim's space; `grouped` says the candidate
    object puts its CODE segment in a group."""
    evidence, unusable = [], []
    calls = [c for c in target.get("call_sites", []) if c["kind"] == "far_call"]
    if space.name == "root":
        for call in calls:
            caller = oracle.spaces[call["space"]]
            evidence.append({"frame": struct.unpack_from("<H", caller.data, call["image_offset"] + 3)[0],
                             "kind": "relocated CALL FAR", "space": caller.name,
                             "image_offset": call["image_offset"]})
        if not evidence:
            evidence += _reached_near_frames(target, space, oracle, hull)
        return evidence, unusable
    entry = space.position(target["segment"], target["offset"])
    for vector in _code_vectors(oracle).values():
        if vector["target_space"] == space.name and vector["target_position"] == entry:
            evidence.append({"frame": vector["target_segment"], "kind": "rtlink-vector",
                             "vector": f"root:{vector['segment']:04x}:{vector['offset']:04x}",
                             "descriptor_index": vector["descriptor_index"]})
    lo, hi = hull
    for call in calls:
        caller = oracle.spaces[call["space"]]
        at = call["image_offset"]
        offset, segment = struct.unpack_from("<HH", caller.data, at + 1)
        row = {"frame": segment, "space": caller.name, "image_offset": at}
        if caller.name == space.name:
            if at < hi and lo < at + 5:
                unusable.append(dict(row, reason="same-overlay CALL FAR inside the object"))
                continue
            evidence.append(dict(row, kind="same-overlay CALL FAR",
                                 relocation_index=next(r["index"] for r in caller.relocations
                                                       if r["image_offset"] == at + 3)))
            continue
        # Memory extent (descriptor paragraphs), not just the file payload, can hold the address.
        holders = sorted(n for n, s in oracle.spaces.items() if n != space.name and
                         0 <= (segment - s.link_segment) * 16 + offset <
                         max(s.size, 16 * (s.descriptor or {}).get("f8", 0)))
        if holders:
            unusable.append(dict(row, reason="link address also held by " + ", ".join(holders)))
            continue
        evidence.append(dict(row, kind="cross-space CALL FAR"))
    site = _site_frame(target, space, oracle, hull, grouped)
    if site:
        (evidence if site[0] == "evidence" else unusable).append(site[1])
    return evidence, unusable


def _check_unplaced(module, placements, symbols):
    """A v4 external address may not fall inside this object's own placed DGROUP segment."""
    lengths = {d["name"]: d["length"] for d in module.segment_defs}
    for name, symbol in symbols.items():
        values = [symbol["offset"]] + [(symbol["offset"] + m["offset"]) & 0xFFFF for m in symbol.get("members", [])]
        for seg, at in placements.items():
            require(not any(at <= v < at + lengths.get(seg, 0) for v in values),
                    f"v4 address of {name} lies inside placed segment {seg}")


def _internal_support(symbols, states, reports):
    """Internal consensus for v4 addresses without witnesses (2026-11-21 review).

    For each linked value S+k whose symbol or member lists no witness, every claimed field
    with that value is proven only if equal fields of the same symbol and k occur at two or
    more distinct original instruction starts, all inside CODE_EXACT claims. One unknown S
    then meets two equations. Different k never support each other. A claim losing support
    withdraws its fields, so the check runs to a fixpoint."""
    need = set()
    for name, symbol in symbols.items():
        if symbol.get("kind") != "dgroup-offset":
            continue
        if not symbol.get("witnesses"):
            need.add((name, 0))
        need.update((name, m["offset"]) for m in symbol.get("members", []) if not m.get("witnesses"))
    by_public = {r["public"]: r for r in reports}
    for state in states.values():
        for field in state["v4"]:
            for equation in state["equations"]:
                if equation.get("kind") == "DGROUP offset16" and equation["offset"] == field["offset"]:
                    equation["support"] = "internal consensus" if field["key"] in need else "witnessed"
    if not need:
        return
    changed = True
    while changed:
        changed = False
        exact = [p for p in states if by_public[p].get("exact")]
        sites = {}
        for public in exact:
            for field in states[public]["v4"]:
                if field["key"] in need and field["equal"]:
                    sites.setdefault(field["key"], set()).add(field["insn"])
        for public in exact:
            lacking = sorted({f["key"] for f in states[public]["v4"]
                              if f["key"] in need and len(sites.get(f["key"], ())) < 2})
            if lacking:
                by_public[public].update(exact=False, state="REFUSED",
                                         reason="v4 address without witness lacks a second equal claimed site: " +
                                         ", ".join(f"{n}+{k}" for n, k in lacking))
                changed = True


def check_group(obj_data, claims, oracle, *, binding=None, group_id=None):
    """Judge every claim; never raises for a claim-level mismatch, only for object-level refusal."""
    module = OmfReader().read(obj_data, "candidate")
    placements = (binding or {}).get("placements", {})
    segment, name, actual = code_segment(module, placed=tuple(placements))
    publics = {}
    for public in module.publics:
        require(public["segment"] == name, "Public outside the CODE segment")
        require(public["name"] not in publics, "Duplicate public")
        require(0 <= public["offset"] < len(actual), "Public outside the initialized CODE segment")
        publics[public["name"]] = public["offset"]
    offsets = sorted(publics.values())
    require(len(set(offsets)) == len(offsets), "Two publics share one offset")
    require(offsets and offsets[0] == 0, "Code before the first public would be unaccounted for")
    require(claims and len({c["target_id"] for c in claims}) == len(claims) and
            len({c["public"] for c in claims}) == len(claims), "Claims must be unique")
    obligations = fixes(module)
    dgroup_members = {module.segment_defs[i - 1]["name"] for g in module.groups if g["name"] == "DGROUP"
                      for i in g["segments"] if 1 <= i <= len(module.segment_defs)}
    fields = set()
    for fix in obligations:
        span = set(range(fix["segment_offset"], fix["segment_offset"] + fix["field_width"]))
        require(not fields.intersection(span) and max(span) < len(actual),
                "Fixup fields overlap or leave the CODE segment")
        fields.update(span)
    resolved, origin, space = [], None, None
    for claim in claims:
        require(claim["public"] in publics, f"Claimed public {claim['public']} is not emitted")
        target, target_space, expected = get_target(claim["target_id"], oracle)
        require(space is None or target_space.name == space.name, "Claims span several spaces")
        space = target_space
        position = space.position(target["segment"], target["offset"])
        start = publics[claim["public"]]
        require(origin is None or position - start == origin,
                "Claims do not share one object placement")
        origin = position - start
        resolved.append((claim, target, expected, start))
    require(0 <= origin and origin + len(actual) <= space.size, "Object placement escapes the space")
    code_index = next(i for i, d in enumerate(module.segment_defs, 1) if d["name"] == name)
    grouped = any(code_index in g["segments"] for g in module.groups)
    frame_rows = {claim["public"]: _frame_evidence(target, space, oracle, (origin, origin + len(actual)), grouped)
                  for claim, target, _, _ in resolved}
    frames = {row["frame"] for evidence, _ in frame_rows.values() for row in evidence}
    require(len(frames) <= 1, "Claims are entered through different original frames")
    window = None
    if frames:
        base = (next(iter(frames)) - space.link_segment) * 16
        window = (base, base + 0x10000)
    symbols, mode, far_symbols, near_symbols = None, None, {}, {}
    if binding is not None:
        require(binding["fixups"] == obligations, "Ordered symbolic fixup obligations changed")
        require(binding["declarations"] == declarations(module), "Bound object declarations changed")
        require(group_id is not None and binding["target_id"] == group_id, "Binding belongs to another group")
        hull = dict(space.address(origin), id=group_id, size=len(actual))
        # Far callees (other files) ground exactly as in the single-function far gate:
        # a reviewed direct entry plus independent relocated CALL FAR witnesses, all
        # outside the whole object. Near callees outside the object ground by an accepted
        # exact owner or an outside original near CALL. Data symbols use the DGROUP modes.
        far_symbols = {n: s for n, s in binding["symbols"].items() if s.get("kind") in FAR_KINDS}
        near_symbols = {n: near_ground(s, hull, oracle) for n, s in binding["symbols"].items()
                        if s.get("kind") == NEAR_KIND}
        data_only = {n: s for n, s in binding["symbols"].items()
                     if n not in far_symbols and n not in near_symbols}
        # Overlay owners too: the field equation depends only on the grounded 16:16 alias,
        # and its segment word is relocated by the owner's own overlay table (bijection below).
        for symbol in far_symbols.values():
            far_ground(symbol, hull, oracle,
                       claimed=[(origin + start, origin + start + len(expected)) for _, _, expected, start in resolved])
        if data_only:
            claimed = [(origin + start, origin + start + len(expected)) for _, _, expected, start in resolved]
            symbols = ground({**binding, "symbols": data_only}, hull, oracle,
                             claimed=claimed if binding["mode"] == OPERAND_MODE else None)
            mode = binding["mode"]
            if mode == OPERAND_MODE:
                _check_unplaced(module, placements, data_only)
        elif "frame" in binding:
            # Verify the DGROUP frame witness even without data symbols (DGROUP base fields).
            ground({**binding, "mode": OPERAND_MODE, "symbols": {}}, hull, oracle)
        else:
            require(binding["mode"] in ("external-far-call-v1",) + DATA_MODES, "Unsupported group binding mode")
            symbols, mode = {}, binding["mode"]

    # Pass 1: extent, decoding, near equations. Pass 2: segment safety. Pass 3: data.
    states, reports, placed_uses, used_near = {}, [], {}, set()
    for claim, target, expected, start in resolved:
        later = [o for o in offsets if o > start]
        end = later[0] if later else len(actual)
        report = {"target_id": claim["target_id"], "public": claim["public"], "object_offset": start,
                  "expected_size": len(expected), "emitted_size": end - start,
                  "expected_sha256": sha(expected), "emitted_sha256": sha(actual[start:end])}
        evidence, unusable = frame_rows[claim["public"]]
        if space.name != "root":
            report.update(frame_evidence=evidence, frame_evidence_refused=unusable)
        reports.append(report)
        try:
            piece = actual[start:end]
            require(len(piece) == len(expected), "Claim extent differs from the reviewed target; trimming forbidden")
            position = origin + start
            mine = [f for f in obligations if start <= f["segment_offset"] < end]
            require(all(f["segment_offset"] + f["field_width"] <= end for f in mine) and
                    not any(f["segment_offset"] < start < f["segment_offset"] + f["field_width"]
                            for f in obligations), "Fixup field crosses the claim boundary")
            own_fields = [f["segment_offset"] - start for f in mine if _own_segment(f, name)]
            tables = _tables(own_fields, piece, start)
            try:
                rows = _decode(piece, tables) if tables else instructions(piece)
            except ValueError:
                require(not mine, "Fixup-bearing claim does not decode completely")
                rows = None
            state = {"start": start, "piece": piece, "expected": expected, "rows": rows,
                     "occupied": set(), "differences": [], "equations": [], "calls": {}, "data": [],
                     "near": [], "far": [], "own": [], "tables": tables, "group_bases": [], "v4": [],
                     "proven_jumps": set(),
                     "fixups": len(mine), "frames": {row["frame"] for row in evidence},
                     "report": report, "position": position,
                     "relocations": [r for r in space.relocations
                                     if position-1 <= r["image_offset"] < position+len(expected)]}
            starts = {i.address for i in rows} if rows else set()
            for fix in mine:
                at = fix["segment_offset"] - start
                if _own_segment(fix, name):
                    in_table = any(lo <= at < hi for lo, hi in tables)
                    # Any decoded disp16/imm16 field qualifies here, including the indirect
                    # `jmp cs:[bx+T]` displacement that selects the jump table.
                    require(in_table or any((i.disp_size == 2 and i.address + i.disp_offset == at) or
                                            (i.imm_size == 2 and i.address + i.imm_offset == at)
                                            for i in rows),
                            "Own-segment field is neither a jump-table word nor an operand field")
                    # MASM may carry the offset in the FIXUPP displacement: the linker adds D + A.
                    addend = (struct.unpack_from("<H", piece, at)[0] + (fix["displacement"] or 0)) & 0xFFFF
                    if in_table:
                        # A table entry must point at an instruction start inside this claim.
                        require(start <= addend < end and (addend - start) in starts,
                                "Jump-table entry does not target an instruction of the claim")
                    state["own"].append({"offset": at, "addend": addend})
                    state["occupied"].update((at, at+1))
                elif fix["self_relative"]:
                    kind, dest, (branch, insn_at, push_cs) = _self_relative(
                        fix, name, publics, near_symbols, piece, at, rows, start, end)
                    # Linear (space-relative) positions: value = S - (P + 2) mod 65536.
                    field = origin + fix["segment_offset"]
                    if kind == "internal":
                        callee_at = origin + dest
                    elif kind == "public":
                        callee_at = origin + publics[dest]
                    else:
                        callee_at = near_symbols[dest]["position"]
                        used_near.add(dest)
                    value = (callee_at - (field + 2)) & 0xFFFF
                    observed = struct.unpack_from("<H", expected, at)[0]
                    label = {"internal": "own-segment rel16", "public": "same-object near16",
                             "external": "external near16"}[kind]
                    row = {"offset": at, "kind": label, "instruction": branch, "push_cs": push_cs,
                           "linked_value": value, "original_value": observed, "equal": value == observed}
                    if kind == "internal":
                        row["destination"] = dest - start
                        state["proven_jumps"].add(insn_at)
                    else:
                        row["symbol"] = dest
                        # Runtime meaning needs CS: the whole call (with its PUSH CS) and the
                        # callee must lie in one witnessed CS window (checked below).
                        state["near"].append({"pair_start": origin + start + insn_at - (1 if push_cs else 0),
                                              "field_end": field + 2,
                                              "callee": dest if kind == "public" else None,
                                              "callee_at": callee_at, "equal": value == observed})
                        # A same-object callee must itself be proven safe; an external near
                        # callee is never assumed to preserve segment context.
                        if branch == "jmp":
                            state["proven_jumps"].add(insn_at)  # a tail jump: control ends here
                        else:
                            state["calls"][insn_at] = dest if kind == "public" else EXTERNAL_NEAR
                    state["equations"].append(row)
                    if value != observed:
                        state["differences"].append(at)
                    state["occupied"].update((at, at+1))
                elif fix["target"].get("name") in far_symbols:
                    require(fix["target"]["name"] not in publics,
                            "Far fixup target resolves to a CODE public of this object")
                    state["far"].append(dict(fix, segment_offset=at))
                    if far_symbols[fix["target"]["name"]].get("kind") not in ("segment-base", "far-data"):
                        state["calls"][at - 1] = None  # a far callee, not a claim
                elif (fix["target"].get("kind") == "segment" and fix["target"].get("name") in placements and
                      fix["loc_type"] == 1 and not fix["self_relative"] and fix["field_width"] == 2):
                    # A field addressing this object's own placed DGROUP segment: P + A. Only
                    # the DGROUP frame (F1, MSC and MASM `ASSUME DS:DGROUP`) adds P; a segment
                    # or target frame would write A alone, so it is refused.
                    require(fix["frame"].get("kind") == "group" and fix["frame"].get("name") == "DGROUP" and
                            fix["target"]["name"] in dgroup_members,
                            "Placed-data fixup must use the DGROUP frame of a DGROUP member segment")
                    require(any(operand_field_of(i, at, candidate=True) for i in rows),
                            "Placed-data fixup is not the address field of one decoded instruction")
                    seg_name = fix["target"]["name"]
                    # MASM may carry the offset in the FIXUPP displacement (T0/T4 with D) instead of
                    # the LEDATA bytes; the linker adds both: P + D + A.
                    addend = (struct.unpack_from("<H", piece, at)[0] + (fix["displacement"] or 0)) & 0xFFFF
                    value = (placements[seg_name] + addend) & 0xFFFF
                    observed = struct.unpack_from("<H", expected, at)[0]
                    state["equations"].append({"offset": at, "kind": "placed data", "segment": seg_name,
                                               "encoded_addend": addend, "placement": placements[seg_name],
                                               "linked_value": value, "original_value": observed,
                                               "equal": value == observed})
                    if value != observed:
                        state["differences"].append(at)
                    state["occupied"].update((at, at+1))
                    if value == observed:  # only proven fields over-determine a placement
                        placed_uses.setdefault(seg_name, set()).add(addend)
                elif (fix["loc_type"] == 2 and not fix["self_relative"] and fix["field_width"] == 2 and
                      fix["target"].get("kind") == "group" and fix["target"].get("name") == "DGROUP"):
                    # `mov ax, DGROUP`: the DGROUP paragraph, grounded by the binding's startup
                    # DS-load frame witness; relocated in MZ at the field itself.
                    require(binding is not None and "frame" in binding and fix["displacement"] is None,
                            "DGROUP base needs a binding with a grounded DGROUP frame")
                    require(piece[at:at+2] == bytes(2), "Only zero encoded DGROUP base addends are proven")
                    value = binding["frame"]["segment"]
                    observed = struct.unpack_from("<H", expected, at)[0]
                    state["equations"].append({"offset": at, "kind": "DGROUP base", "linked_segment": value,
                                               "original_segment": observed, "equal": value == observed})
                    if value != observed:
                        state["differences"].append(at)
                    state["occupied"].update((at, at+1))
                    state["group_bases"].append(at)
                else:
                    require(fix["target"].get("name") not in publics,
                            "Data fixup target resolves to a CODE public of this object")
                    state["data"].append(dict(fix, segment_offset=at))
            require(not state["relocations"] or state["far"] or state["group_bases"],
                    "Original MZ relocations need far CALL fixups in the claim")
            states[claim["public"]] = state
        except ValueError as error:
            report.update(exact=False, state="REFUSED", reason=str(error))

    # Original CS: a claim runs in the witnessed frame if a relocated CALL FAR names
    # it directly, or a claim already proven so reaches it by an equal near call whose
    # whole PUSH CS; CALL pair and callee lie inside that frame's 64K window.
    def in_window(near):
        return (window is not None and window[0] <= near["pair_start"] and near["field_end"] <= window[1]
                and window[0] <= near["callee_at"] < window[1])

    cs_proven = {p for p, s in states.items() if s["frames"]}
    changed = True
    while changed:
        changed = False
        for public in list(cs_proven):
            for near in states[public]["near"]:
                if near["equal"] and in_window(near) and near["callee"] in states and \
                        near["callee"] not in cs_proven:
                    cs_proven.add(near["callee"])
                    changed = True
    for public, state in list(states.items()):
        if state["own"] and public in cs_proven and window is not None:
            # Own-segment word = segment-relative offset in the witnessed frame: origin - base + A.
            for own in state["own"]:
                value = (origin - window[0] + own["addend"]) & 0xFFFF
                observed = struct.unpack_from("<H", state["expected"], own["offset"])[0]
                state["equations"].append({"offset": own["offset"], "kind": "own-segment offset16",
                                           "encoded_addend": own["addend"], "linked_value": value,
                                           "original_value": observed, "equal": value == observed})
                if value != observed:
                    state["differences"].append(own["offset"])
        if not state["near"] and not state["own"]:
            continue
        position = state["position"]
        reason = ("Near call or own-segment word lacks an independently witnessed original frame"
                  if public not in cs_proven else
                  "Near call leaves the witnessed original CS window"
                  if not all(in_window(n) for n in state["near"]) else
                  "Own-segment word lies outside the witnessed original CS window"
                  if state["own"] and not (window[0] <= position and
                                           position + len(state["piece"]) <= window[1]) else None)
        if reason:
            state["report"].update(exact=False, state="REFUSED", reason=reason)
            del states[public]

    # A claim preserves DS/ES/SS only if its own code does, control cannot leave it
    # except by return or an allowed call, and every call goes to a claim that does too.
    # Unclaimed drafts are never assumed safe.
    safe, changed = set(), True
    while changed:
        changed = False
        for public, state in states.items():
            if public in safe or state["rows"] is None:
                continue
            # Far callees in other files keep DS/SS per the MSC far-call ABI, as the
            # single-function far gate also assumes; drafts and unproved claims do not.
            allowed = {at for at, callee in state["calls"].items() if callee is None or callee in safe}
            try:
                preserve_segments(state["rows"], allowed, es_ds=mode == IMMEDIATE_MODE)
                _contained(state["rows"], len(state["piece"]), state["proven_jumps"])
            except ValueError:
                continue
            safe.add(public)
            changed = True

    used_symbols, used_far = set(), set()
    for report in reports:
        state = states.get(report["public"])
        if state is None:
            continue
        try:
            relocation_proof = {}
            if state["far"]:
                sites = []
                by_address = {i.address: i for i in state["rows"]}
                for fix in state["far"]:
                    at, ref = fix["segment_offset"], fix["target"]
                    symbol = far_symbols[ref["name"]]
                    # LOC5 (loader-resolved offset16) writes the same value as LOC1 here.
                    if symbol.get("kind") == "far-data" and fix["loc_type"] in (1, 5) and not fix["self_relative"]:
                        # Offset half of a far data pointer: O within the object's own segment.
                        require(fix["field_width"] == 2 and ref["kind"] == "external" and fix["displacement"] is None and
                                fix["frame"] == {"kind": "target_frame", "target": ref},
                                "Unsupported far data offset fixup shape")
                        addend = struct.unpack_from("<H", state["piece"], at)[0]
                        require(addend == 0 or addend in {m["offset"] for m in symbol.get("members", [])},
                                "Far data addends must be zero or independently witnessed members")
                        linked = (symbol["offset"] + addend) & 0xFFFF
                        observed = struct.unpack_from("<H", state["expected"], at)[0]
                        state["equations"].append({"offset": at, "kind": "far-data offset", "symbol": ref["name"],
                                                   "encoded_addend": addend, "linked_offset": linked,
                                                   "original_offset": observed, "equal": linked == observed})
                        if linked != observed:
                            state["differences"].append(at)
                        state["occupied"].update(range(at, at+2))
                        used_far.add(ref["name"])
                        continue
                    if symbol.get("kind") in ("segment-base", "far-data") and fix["loc_type"] == 2:
                        # LOC2 base16 of an external far segment (`mov ax, seg Table`): the
                        # linker writes that segment's paragraph, relocated in MZ at the field.
                        # F5, or F2 naming the same external (MASM `mov ax, SEG X`): X's own frame.
                        same_external = {k: fix["frame"].get(k) for k in ("kind", "index", "name")} ==                             {"kind": "external", "index": ref.get("index"), "name": ref.get("name")}
                        require(fix["loc_type"] == 2 and fix["field_width"] == 2 and not fix["self_relative"] and
                                ref["kind"] == "external" and fix["displacement"] is None and
                                (fix["frame"] == {"kind": "target_frame", "target": ref} or same_external),
                                "Unsupported segment-base fixup shape")
                        require(state["piece"][at:at+2] == bytes(2), "Only zero encoded segment addends are proven")
                        observed = struct.unpack_from("<H", state["expected"], at)[0]
                        state["equations"].append({"offset": at, "kind": "segment-base", "symbol": ref["name"],
                                                   "linked_segment": symbol["segment"], "original_segment": observed,
                                                   "equal": symbol["segment"] == observed})
                        if symbol["segment"] != observed:
                            state["differences"].append(at)
                        state["occupied"].update(range(at, at+2))
                        sites.append({"site": state["position"] + at, "offset": at, "symbol": ref["name"]})
                        used_far.add(ref["name"])
                        continue
                    # F5 (target frame, MSC) or F2 naming the same external as the target (MASM
                    # `call far ptr X`): both frame the pointer by X's own segment.
                    same_external = {k: fix["frame"].get(k) for k in ("kind", "index", "name")} ==                         {"kind": "external", "index": ref.get("index"), "name": ref.get("name")}
                    require(fix["loc_type"] == 3 and fix["field_width"] == 4 and not fix["self_relative"] and
                            ref["kind"] == "external" and ref["method"] == 6 and fix["displacement"] is None and
                            (fix["frame"] == {"kind": "target_frame", "target": ref} or same_external),
                            "Unsupported far CALL fixup equation/frame/displacement")
                    insn = by_address.get(at - 1)
                    require(insn is not None and insn.size == 5 and bytes(insn.bytes)[:1] == b"\x9a",
                            "Far fixup is not a complete unprefixed 9A CALL operand")
                    require(state["piece"][at:at+4] == bytes(4), "Only zero encoded far addends are proven")
                    value = (symbol["offset"], symbol["segment"])
                    observed = struct.unpack_from("<HH", state["expected"], at)
                    state["equations"].append({"offset": at, "kind": "far-call", "symbol": ref["name"],
                                               "linked_offset": value[0], "linked_segment": value[1],
                                               "original_offset": observed[0], "original_segment": observed[1],
                                               "equal": value == observed})
                    if value != observed:
                        state["differences"].append(at)
                    state["occupied"].update(range(at, at+4))
                    sites.append({"site": state["position"] + at + 2, "offset": at, "symbol": ref["name"]})
                    used_far.add(ref["name"])
                sites += [{"site": state["position"] + g, "offset": g, "symbol": "DGROUP"} for g in state["group_bases"]]
                relocation_proof = relocation_order(state["relocations"], sites,
                                                    [r["index"] for r in state["relocations"]])
            if state["group_bases"] and not state["far"]:
                relocation_proof = relocation_order(
                    state["relocations"],
                    [{"site": state["position"] + g, "offset": g, "symbol": "DGROUP"} for g in state["group_bases"]],
                    [r["index"] for r in state["relocations"]])
            if state["data"]:
                require(symbols is not None, "DGROUP fixups require a grounded group binding")
                missing = sorted({f["target"].get("name") for f in state["data"]} - set(symbols))
                require(not missing, "DGROUP fixup targets lack grounded binding symbols: " + ", ".join(map(str, missing)))
                # v4 proves offset bytes only and claims no DS association, so it needs no
                # segment-context proof; the older modes keep theirs.
                require(mode == OPERAND_MODE or report["public"] in safe,
                        "DGROUP access after a call into code not proven to preserve segment context")
                allowed = {at for at, callee in state["calls"].items() if callee is None or callee in safe}
                data_context(module, state["rows"], allowed, mode=mode, placed=tuple(placements))
                found, unequal = data_equations(state["data"], symbols, name, state["piece"], state["expected"],
                                                state["rows"], mode, state["occupied"])
                state["equations"] += [dict(e, kind="DGROUP offset16") for e in found]
                state["differences"] += unequal
                if mode == OPERAND_MODE:
                    for e in found:
                        insn = next(i for i in state["rows"] if i.address <= e["offset"] < i.address + i.size)
                        state["v4"].append({"key": (e["symbol"], e["encoded_addend"]), "equal": e["equal"],
                                            "insn": state["position"] + insn.address, "offset": e["offset"]})
                used_symbols.update(f["target"]["name"] for f in state["data"])
            piece, expected, occupied = state["piece"], state["expected"], state["occupied"]
            differences = state["differences"] + [i for i in range(len(piece))
                                                  if i not in occupied and piece[i] != expected[i]]
            report.update(exact=not differences, state="CODE_EXACT" if not differences else "CANDIDATE_C",
                          first_difference=min(differences, default=None),
                          mismatch_count=len(differences), fixups=state["fixups"],
                          relocations=len(state["relocations"]),
                          covered_relocation_indices=[r["index"] for r in state["relocations"]],
                          equations=state["equations"], ordinary_bytes_compared=len(piece) - len(occupied),
                          **{k: v for k, v in relocation_proof.items()
                             if k in ("relocation_order", "relocation_order_debt", "relocation_groups")})
        except ValueError as error:
            report.update(exact=False, state="REFUSED", reason=str(error))
    if mode == OPERAND_MODE and binding is not None:
        _internal_support(binding["symbols"], states, reports)
    # A refused claim never evaluated its data fields; report it instead of masking the reason.
    if symbols is not None and not any(r["state"] == "REFUSED" for r in reports):
        require(set(symbols) == used_symbols, "Missing or unused grounded data symbol")
        require(set(far_symbols) == used_far, "Missing or unused grounded far symbol")
    if not any(r["state"] == "REFUSED" for r in reports):
        require(set(near_symbols) == used_near, "Missing or unused grounded near-code entry")
    placement_report = _check_placements(module, placements, placed_uses, binding, space, oracle)
    claimed = {c["public"] for c in claims}
    return {"exact": all(r["exact"] for r in reports), "object_sha256": sha(obj_data),
            "placements": placement_report,
            "space": space.name, "origin": origin, "emitted_size": len(actual),
            "frame": next(iter(frames)) if frames else None,
            "segment": segment, "claims": reports,
            "drafts": sorted(({"public": p, "object_offset": o} for p, o in publics.items() if p not in claimed),
                             key=lambda d: d["object_offset"]),
            "unreferenced_external_declarations": [e for e in module.externals
                                                   if e not in {f["target"].get("name") for f in obligations}],
            "fixup_thread_declarations": [entry for record in module.fixups for entry in record["decoded"]],
            "record_types": [r["type"] for r in module.records], "proof_scope": GROUP_PROOF_SCOPE}


def compile_group(source_text, profile, flags, claims, workdir, *, binding=None, group_id=None, language="c"):
    """Compile (C) or assemble (MASM) exactly the given source text, the bytes the caller
    hashed, and judge it. ASM claims report ASM_EXACT/CANDIDATE_ASM."""
    from pathlib import Path
    from oracle import Oracle
    require(language in ("c", "asm"), "Unknown source language")
    oracle = Oracle.load()
    work = Path(workdir)
    if language == "asm":
        from assembler import assemble_asm
        work.mkdir(parents=True, exist_ok=True)
        staged = work / "GROUP.ASM"
        staged.write_bytes(source_text.encode("ascii"))
        result = assemble_asm(staged, profile, flags=flags, workdir=work / "asm")
    else:
        from compiler import compile_c
        result = compile_c(source_text, profile, flags=flags, workdir=work)
    require(result.ok, "Historical compilation failed: " + result.log)
    report = check_group(result.obj_bytes, claims, oracle, binding=binding, group_id=group_id)
    if language == "asm":
        for claim in report["claims"]:
            claim["state"] = {"CODE_EXACT": "ASM_EXACT", "CANDIDATE_C": "CANDIDATE_ASM"}.get(claim["state"],
                                                                                           claim["state"])
    report["language"] = language
    return result, report
