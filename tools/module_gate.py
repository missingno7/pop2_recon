OMF_ALIGNMENT = {1: 1, 2: 2, 3: 16, 4: 256, 5: 4}  # SEGDEF A field: byte, word, para, page, dword


def alignment_violations(rows):
    """Refutation only (whole-link alignment, 2026-11-22; o10_trial): a linker starts every object's
    contribution at a multiple of its SEGDEF alignment. Root and overlay sections and DGROUP start on
    paragraphs, so a space position or DGROUP offset keeps the absolute residue. `rows` are
    (component, segment, alignment code, address); returns `alignment:COMPONENT:SEGMENT@ADDRESS` keys."""
    return {f"alignment:{c}:{s}@{a:x}" for c, s, code, a in rows if a % OMF_ALIGNMENT.get(code, 1)}


def immediate_witness_violations(recipes, oracle):
    """Refutation only (2026-11-23): a v4 symbol or member whose every witness is a MOV/PUSH immediate that the
    original code does not use as an address (`binding.immediate_is_address`). Such an immediate may be a plain number
    that happens to equal the address, so it proves nothing. Returns stable keys `imm:GROUP:NAME[+k]@address`."""
    from binding import immediate_is_address, instructions, operand_field
    from common import project_path

    def ambiguous(spec):
        insn = instructions(bytes.fromhex(spec["bytes_hex"]))[0]
        return (operand_field(insn, spec["operand_offset"]) == "immediate" and
                not immediate_is_address(oracle, spec["space"], spec["image_offset"]))

    found = set()
    for owner, recipe in recipes:
        if owner.get("kind") == "PINNED_RUNTIME" or "binding" not in recipe:
            continue
        gid = recipe.get("group_id") or recipe["name"]
        for name, symbol in read_json_shared(project_path(recipe["binding"])).get("symbols", {}).items():
            if symbol.get("kind") != "dgroup-offset" or type(symbol.get("offset")) is not int:
                continue
            rows = [(name, symbol["offset"], symbol.get("witnesses") or [])]
            rows += [(f"{name}+{m['offset']:#x}", symbol["offset"] + m["offset"], m.get("witnesses") or [])
                     for m in symbol.get("members", [])]
            for key, address, witnesses in rows:
                if key == name and symbol.get("extent"):
                    continue  # the original copies through this address
                if witnesses and all("operand_offset" in w and ambiguous(w) for w in witnesses):
                    found.add(f"imm:{gid}:{key}@{address & 0xFFFF:04x}")
    return found


def name_consistency_violations(recipes, vectors=None):
    """Refutation only (whole-link names, 2026-11-22; o10_trial): a real link has one definition per public
    name and resolves one external name to one address. Returns stable keys:
    - `duplicate-public:NAME` for a public defined by more than one accepted component (claims, drafts,
      data publics, pinned runtime publics);
    - `multi-address:NAME` for a binding symbol name grounded at different addresses by different bindings
      (v4 DGROUP offsets, far 16:16 aliases);
    - `alias:GROUP:NAME` for a far code entry symbol of GROUP whose entry is an accepted claim or draft
      published under another name (the linker resolves EXTDEFs by name, never by address; RTLink 6.10
      symbol ids are case-insensitive, o11_relorder);
    - `same-entry:GROUP:TARGET` for one binding naming the same code entry under several names (one
      original declaration, two in the source). Names that one pinned library member itself defines at that
      very address (`__aFlmul`/`__aFulmul`) are the library's publics, not two declarations of one entry;
    - `vector-alias:GROUP:NAME` (2026-11-24, v1.1 trial link) for a call through an original overlay vector whose
      destination is accepted under another name: RTLink vectors a name, so another name calls the overlay directly.
      `vectors` maps (segment, offset) of each original vector to its target id;
    - `data-alias:GROUP:NAME` for a DGROUP symbol at the address of an accepted data public with another name."""
    from common import project_path
    found = {f"duplicate-public:{n}" for n, c in accepted_public_names(recipes).items() if c > 1}
    entry_names = {}
    for owner, recipe in recipes:
        rows = recipe.get("claims", []) + recipe.get("drafts", []) + ([recipe] if "target_id" in recipe else [])
        for row in rows:
            if "target_id" in row and "public" in row:
                entry_names.setdefault(row["target_id"], set()).add(row["public"])
    data_names = {}
    for owner, recipe in recipes:
        for row in recipe.get("data_publics", []):
            data_names.setdefault(row["address"], set()).add(row["name"].upper())
    addresses = {}
    runtime_names = runtime_public_positions(recipes)
    for owner, recipe in recipes:
        if owner.get("kind") == "PINNED_RUNTIME" or "binding" not in recipe:
            continue
        gid = recipe.get("group_id") or recipe.get("name")
        entries = {}
        for name, symbol in read_json_shared(project_path(recipe["binding"])).get("symbols", {}).items():
            target = symbol.get("entry_target_id")
            if type(target) is str:
                entries.setdefault(target, set()).add(name)
                if target in entry_names and name.upper() not in {n.upper() for n in entry_names[target]}:
                    found.add(f"alias:{gid}:{name}")
            if symbol.get("kind") == "rtlink-vector":
                names = entry_names.get((vectors or {}).get((symbol["segment"], symbol["offset"])), set())
                if names and name.upper() not in {n.upper() for n in names}:
                    found.add(f"vector-alias:{gid}:{name}")
            if symbol.get("kind") == "dgroup-offset" and                     name.upper() not in data_names.get(symbol.get("offset"), {name.upper()}):
                found.add(f"data-alias:{gid}:{name}")
            if symbol.get("kind") == "dgroup-offset" and type(symbol.get("offset")) is int:
                addresses.setdefault(name, set()).add(("DS", symbol["offset"]))
            elif symbol.get("kind") in FAR_KINDS and type(symbol.get("segment")) is int:
                at = (symbol["segment"], symbol.get("offset"))
                if symbol["kind"] == "rtlink-vector" and at in (vectors or {}):  # the name is the vector's destination
                    at = tuple(int(q, 16) for q in vectors[at].split(":")[1:])
                addresses.setdefault(name, set()).add(("FAR", *at))
        for t, names in entries.items():
            if len(names) > 1 and not names <= runtime_names.get(entry_position(t), set()):
                found.add(f"same-entry:{gid}:{t}")
    found |= {f"multi-address:{n}" for n, a in addresses.items() if len(a) > 1}
    return found


def entry_position(target_id):
    """(space, linear address) of a SPACE:SEG:OFF entry id."""
    space, segment, offset = target_id.rsplit(":", 2)
    return space, int(segment, 16) * 16 + int(offset, 16)


def runtime_public_positions(recipes):
    """(space, linear address) -> publics that one pinned library member defines at that address."""
    from pathlib import Path
    from omf import OmfReader
    out = {}
    for owner, recipe in recipes:
        if owner.get("kind") != "PINNED_RUNTIME" or len(recipe.get("publics", [])) < 2:
            continue
        with open(Path(recipe["library_path"]), "rb") as f:
            f.seek(recipe["archive_offset"])
            raw = f.read(recipe["member_extent"])
        require(sha(raw) == recipe["member_sha256"], "Pinned runtime member identity changed")
        module = OmfReader(overwrite_ledata=True, library_records=True).read(raw, recipe["name"])
        start = recipe["segment"] * 16 + recipe["offset"]
        for public in module.publics:
            if public["segment"] == recipe["object_segment"]:
                out.setdefault((recipe["space"], start + public["offset"]), set()).add(public["name"])
    return out


def accepted_public_names(recipes):
    """name -> how many accepted components define it (code, drafts, data, runtime members)."""
    counts = {}
    for owner, recipe in recipes:
        if owner.get("kind") == "PINNED_RUNTIME":
            names = list(recipe.get("publics", []))
        elif recipe.get("kind") == "same_source_group":
            names = ([c["public"] for c in recipe["claims"]] + [d["public"] for d in recipe.get("drafts", [])] +
                     [d["name"] for d in recipe.get("data_publics", [])])
        elif recipe.get("kind") == DATA_GROUP_KIND:
            names = [d["name"] for d in recipe.get("data_publics", [])]
        elif recipe.get("kind") == "manager_asm":
            names = [p["name"] for p in recipe["publics"]]
        else:
            names = [recipe["public"]] if "public" in recipe else []
        for n in names:
            counts[n] = counts.get(n, 0) + 1
    return counts


def _archive_public(name, symbol, oracle):
    """Ground an external DGROUP symbol by a data public of a pinned library member (2026-11-23; `__ctype`).

    The member's placed segment must be fixup-free, fully initialized and at least 16 bytes long, and equal
    original DGROUP bytes that occur once and hold no relocated word. Its library must be one that accepted runtime
    recipes pin. No accepted component may define the name or place data over the segment."""
    from pathlib import Path
    from common import project_path
    from omf import OmfReader
    spec = symbol["archive"]
    require(set(symbol) <= {"kind", "group", "provider", "offset", "context", "archive"} and
            symbol.get("group") == "DGROUP" and symbol.get("provider") == "runtime" and
            set(spec) == {"library_path", "library_sha256", "archive_offset", "member_extent", "member_sha256",
                          "segment", "placement", "dgroup_segment"}, "Unsupported archive data public symbol")
    recipes = _accepted_recipes()
    require(any(o.get("kind") == "PINNED_RUNTIME" and r.get("library_sha256") == spec["library_sha256"]
                for o, r in recipes), "Archive provider library is not one an accepted runtime recipe pins")
    library = Path(spec["library_path"]).read_bytes()
    raw = library[spec["archive_offset"]:spec["archive_offset"] + spec["member_extent"]]
    require(sha(library) == spec["library_sha256"] and sha(raw) == spec["member_sha256"],
            "Archive provider library or member identity changed")
    module = OmfReader(overwrite_ledata=True, library_records=True).read(raw, "member")
    seg, p = spec["segment"], spec["placement"]
    content = module.segments.get(seg)
    length = next((d["length"] for d in module.segment_defs if d["name"] == seg), 0)
    members = {module.segment_defs[i - 1]["name"] for g in module.groups if g["name"] == "DGROUP"
               for i in g["segments"] if 1 <= i <= len(module.segment_defs)}
    require(seg in members and content is not None and length >= 16 and
            _initialized_with_alignment_holes(module.initialized_ranges.get(seg, []), length) and
            not any(f["segment"] == seg for f in fixes(module)),
            "Archive provider segment is not fixup-free initialized DGROUP data")
    home, dgroup = _dgroup_home({"dgroup_segment": spec["dgroup_segment"]}, oracle.spaces["root"], oracle)
    start = dgroup + p
    require(home.data[start:start + length] == content and _occurs_once(home, dgroup, content) and
            not any(start - 1 <= r["image_offset"] < start + length for r in home.relocations),
            f"Placement of {name} is not fixed by unique original DGROUP content")
    own = sorted(q["offset"] for q in module.publics if q["segment"] == seg)
    entry = [q["offset"] for q in module.publics if q["segment"] == seg and q["name"] == name]
    require(len(entry) == 1 and symbol["offset"] == p + entry[0] and accepted_public_names(recipes).get(name, 0) == 0,
            f"{name} is not the single data public of that archive member")
    span = min([o for o in own if o > entry[0]], default=length) - entry[0]
    for _, other in recipes:
        if "binding" not in other or other.get("kind") not in ("same_source_group", DATA_GROUP_KIND):
            continue
        other_binding = read_json_shared(project_path(other["binding"]))
        lengths = {d["name"]: d["length"] for d in other_binding["declarations"]["segments"]}
        for oseg, q in other_binding.get("placements", {}).items():
            require(not (q < p + length and p < q + lengths[oseg]),
                    f"Archive segment of {name} overlaps placed {oseg} of {other['name']}")
    return {"kind": PUBLIC_KIND, "offset": symbol["offset"], "span": span, "provider": "runtime",
            "segment": seg, "range": (p, p + length)}


def _linker_public(name, symbol, oracle):
    """Ground a DGROUP symbol the linker itself defines (`_end`, `_edata`) by a pinned library member that uses it.

    The member's CODE is located by its ordinary (non-fixup) bytes, at least 64 of them, matching the original at
    exactly one root position; every fixup of that code to `name` must then read the same linked value."""
    from pathlib import Path
    from omf import OmfReader
    spec = symbol["archive"]
    require(set(symbol) <= {"kind", "group", "provider", "offset", "context", "archive"} and name in ("_end", "_edata", "_END",
                                                                                                     "_EDATA") and
            symbol.get("group") == "DGROUP" and
            set(spec) == {"library_path", "library_sha256", "archive_offset", "member_extent", "member_sha256", "segment"},
            "Unsupported linker symbol")
    library = Path(spec["library_path"]).read_bytes()
    raw = library[spec["archive_offset"]:spec["archive_offset"] + spec["member_extent"]]
    require(sha(library) == spec["library_sha256"] and sha(raw) == spec["member_sha256"] and
            any(o.get("kind") == "PINNED_RUNTIME" and r.get("library_sha256") == spec["library_sha256"]
                for o, r in _accepted_recipes()), "Linker symbol witness library or member identity changed")
    module = OmfReader(overwrite_ledata=True, library_records=True).read(raw, "member")
    code = module.segments[spec["segment"]]
    fields = [f for f in fixes(module) if f["segment"] == spec["segment"]]
    masked = {q for f in fields for q in range(f["segment_offset"], f["segment_offset"] + f["field_width"])}
    ordinary = [i for i in range(len(code)) if i not in masked]
    pattern = b"".join(b"." if i in masked else re.escape(code[i:i + 1]) for i in range(len(code)))
    hits = [m.start() for m in re.finditer(b"(?=" + pattern + b")", oracle.spaces["root"].data, re.S)]
    require(len(ordinary) >= 64 and len(hits) == 1, "Linker symbol witness code is not at one original position")
    values = set()
    for f in fields:
        if f["target"].get("kind") == "external" and f["target"].get("name").upper() == name.upper():
            require(f["loc_type"] == 1 and not f["self_relative"], "Unsupported linker symbol field")
            stored = struct.unpack_from("<H", code, f["segment_offset"])[0] + (f["displacement"] or 0)
            values.add((struct.unpack_from("<H", oracle.spaces["root"].data, hits[0] + f["segment_offset"])[0] - stored) & 0xFFFF)
    require(values == {symbol["offset"]}, f"{name} is not the value the original startup code uses")
    return {"kind": PUBLIC_KIND, "offset": symbol["offset"], "span": 0x10000 - symbol["offset"], "provider": "linker",
            "segment": "", "range": (symbol["offset"], symbol["offset"])}


def _provider_public(name, symbol, oracle, group_id, own_names):
    """Ground an external DGROUP symbol by the data public of that name in another accepted
    group (2026-11-22). The linker resolves the EXTDEF by name, so the value is S + A with
    S = P + o: P the provider's placement of the segment, fixed by initialized content that
    occurs once in the original DGROUP image, and o the public's offset in the provider's
    freshly validated object. The addend must stay inside the public's span."""
    import json
    from common import project_path
    if "archive" in symbol:
        return (_linker_public if symbol.get("provider") == "linker" else _archive_public)(name, symbol, oracle)
    require(set(symbol) <= {"kind", "group", "provider", "offset", "context"} and symbol.get("group") == "DGROUP" and
            type(symbol.get("offset")) is int and type(symbol.get("provider")) is str,
            "Unsupported provider data public symbol")
    provider_id = symbol["provider"]
    require(provider_id != group_id and name not in own_names,
            "A provider data public must be defined by another accepted group")
    recipes = _accepted_recipes()
    if provider_id in EXTRA_PROVIDERS:
        recipe = EXTRA_PROVIDERS[provider_id]
        recipes = [(o, r) for o, r in recipes if r.get("group_id") != provider_id] + [({}, recipe)]
    else:
        found = [r for _, r in recipes if r.get("kind") in ("same_source_group", DATA_GROUP_KIND) and
                 r.get("group_id") == provider_id]
        require(len(found) == 1, f"Provider {provider_id} is not one accepted same-source or data-only group")
        recipe = found[0]
    # Linker identity: exactly one accepted definition of the name, and it is this data public.
    require(accepted_public_names(recipes).get(name) == 1,
            f"{name} is not defined exactly once among accepted components")
    entries = [d for d in recipe.get("data_publics", []) if d["name"] == name]
    require(len(entries) == 1, f"{name} is not a data public of accepted provider {provider_id}")
    entry = entries[0]
    require(entry["unique"] is True, f"Placement of {name} is not fixed by unique initialized content")
    raw = project_path(recipe["binding"]).read_bytes()
    require(sha(raw) == recipe["binding_sha256"], "Provider binding changed without acceptance")
    provider_binding = json.loads(raw)
    seg = entry["segment"]
    p = provider_binding["placements"][seg]
    length = next(d["length"] for d in provider_binding["declarations"]["segments"] if d["name"] == seg)
    require(0 <= entry["offset"] and entry["span"] > 0 and entry["offset"] + entry["span"] <= length and
            entry["address"] == p + entry["offset"] and symbol["offset"] == entry["address"],
            f"Provider data public {name} address or span disagrees with its placement")
    # Recheck from the original image: the placed window occurs once, and its relocated words are
    # exactly the provider's own far-pointer and segment-word fields (its pinned fixups).
    home, dgroup = _dgroup_home(provider_binding, oracle.spaces[recipe["space"]], oracle)
    start = dgroup + p
    relocated = {r["image_offset"] - start for r in home.relocations
                 if start - 1 <= r["image_offset"] < start + length}
    own = {f["segment_offset"] + (2 if f["loc_type"] == 3 else 0) for f in provider_binding.get("fixups", [])
           if f["segment"] == seg and f["loc_type"] in (2, 3)}
    require(length >= 2 and start + length <= home.size and
            _occurs_once(home, dgroup, home.data[start:start + length]) and relocated == own,
            f"Placement of {name} is not fixed by unique original DGROUP content")
    # One DGROUP byte has one defining object: no other accepted group places data over it.
    for _, other in recipes:
        # The judged group's own accepted recipe is the version this publication replaces; its
        # new placements are checked against the provider separately (own-placement overlap).
        if other.get("kind") != "same_source_group" or other.get("group_id") in {provider_id, group_id} | REPLACING or                 "binding" not in other:
            continue
        other_binding = read_json_shared(project_path(other["binding"]))
        lengths = {d["name"]: d["length"] for d in other_binding["declarations"]["segments"]}
        for oseg, q in other_binding.get("placements", {}).items():
            require(not (q < p + length and p < q + lengths[oseg]),
                    f"Provider segment of {name} overlaps placed {oseg} of {other['name']}")
    return {"kind": PUBLIC_KIND, "offset": entry["address"], "span": entry["span"], "provider": provider_id,
            "segment": seg, "range": (p, p + length)}


def _internal_support(symbols, states, reports, conditional=frozenset()):
    """Internal consensus for v4 addresses without witnesses (2026-11-21 review).

    For each linked value S+k whose symbol or member lists no witness, every claimed field
    with that value is proven only if equal fields of the same symbol and k occur at two or
    more distinct original instruction starts, all inside CODE_EXACT claims. One unknown S
    then meets two equations. Different k never support each other. A claim losing support
    withdraws its fields, so the check runs to a fixpoint.

    A member S+h may carry an `extent` L (an array inside the variable, e.g. the records after a count): the original
    shows that [S+h, S+h+L) is one object, so a member inside it is as supported as S+h (2026-11-24)."""
    need, provided = set(), {n for n, s in symbols.items() if s.get("kind") == PUBLIC_KIND}
    for name, symbol in symbols.items():
        if symbol.get("kind") != "dgroup-offset" or symbol.get("unproven"):
            continue
        if not symbol.get("witnesses") and not symbol.get("fit"):
            need.add((name, 0))
        extent = (symbol.get("extent") or {}).get("length", 0)
        need.update((name, m["offset"]) for m in symbol.get("members", [])
                    if not m.get("witnesses") and not m["offset"] < extent and not m.get("unproven") and
                    not m.get("fit") and not m.get("floor"))
    inner = [(name, m["offset"], m["extent"]["length"]) for name, s in symbols.items() if s.get("kind") == "dgroup-offset"
             for m in s.get("members", []) if m.get("extent")]
    by_public = {r["public"]: r for r in reports}
    # An aggregate whose base has no witness: its in-extent members stand only on the base's own consensus.
    bases = {name: s["extent"]["length"] for name, s in symbols.items()
             if s.get("kind") == "dgroup-offset" and s.get("extent") and not s.get("witnesses") and
             s["extent"].get("kind") != "index" and not s.get("fit")}
    # A fitted object (no witness, one place between its neighbours): its claimed fields still have to agree at two
    # or more distinct original instruction starts, anywhere in the object.
    fitted = {name: s["extent"]["length"] for name, s in symbols.items() if s.get("kind") == "dgroup-offset" and s.get("fit")}
    other = {(name, m["offset"]): label for name, s in symbols.items() if s.get("kind") == "dgroup-offset"
             for m in s.get("members", []) for label in ("fit", "floor") if m.get(label)}
    for state in states.values():
        for field in state["v4"]:
            for equation in state["equations"]:
                if equation.get("kind") == "DGROUP offset16" and equation["offset"] == field["offset"]:
                    symbol = symbols.get(field["key"][0], {})
                    in_extent = (field["key"][1] and 0 < field["key"][1] < (symbol.get("extent") or {}).get("length", 0)
                                 and not any(m["offset"] == field["key"][1] and m.get("witnesses")
                                             for m in symbol.get("members", [])))
                    equation["support"] = ("internal consensus" if field["key"] in need else
                                           "fitted object" if field["key"][0] in fitted or
                                           other.get(field["key"]) == "fit" else
                                           "index floor" if other.get(field["key"]) == "floor" else
                                           "accepted provider public" if field["key"][0] in provided else
                                           "aggregate extent" if in_extent else "witnessed")
    if not need and not fitted:
        return
    changed = True
    while changed:
        changed = False
        exact = [p for p in states if by_public[p].get("exact") and p not in conditional]
        sites = {}
        for public in exact:
            for field in states[public]["v4"]:
                if field["key"] in need and field["equal"]:
                    sites.setdefault(field["key"], set()).add(field["insn"])
                if field["equal"] and field["key"][1] < fitted.get(field["key"][0], 0):
                    sites.setdefault((field["key"][0], "fit"), set()).add(field["insn"])

        def supported(key):
            return key not in need or len(sites.get(key, ())) >= 2
        covered = [(name, base, length) for name, base, length in inner if supported((name, base))]
        for public in exact:
            lacking = sorted({f["key"] for f in states[public]["v4"]
                              if not supported(f["key"]) and
                              not any(f["key"][0] == name and base < f["key"][1] < base + length
                                      for name, base, length in covered)} |
                             {(f["key"][0], 0) for f in states[public]["v4"]
                              if f["key"][1] < bases.get(f["key"][0], 0) and len(sites.get((f["key"][0], 0), ())) < 2} |
                             {f["key"] for f in states[public]["v4"]
                              if f["key"][0] in fitted and len(sites.get((f["key"][0], "fit"), ())) < 2})
            if lacking:
                by_public[public].update(exact=False, state="REFUSED",
                                         reason="v4 address without witness lacks a second equal claimed site: " +
                                         ", ".join(f"{n}+{k}" for n, k in lacking))
                changed = True


def _far_consensus(far_symbols, states, reports, conditional):
    """Far data addresses and far callees marked `consensus` (no outside witness): every claimed field with that
    (symbol, addend) needs equal fields at two or more distinct original instruction starts, all in
    CODE_EXACT claims, exactly as `_internal_support` requires for v4 (2026-11-23)."""
    need = set()
    for name, symbol in far_symbols.items():
        if symbol.get("kind") == "far-data":
            need.update([(name, 0)] if symbol.get("consensus") else [])
            need.update((name, m["offset"]) for m in symbol.get("members", []) if m.get("consensus"))
        elif symbol.get("consensus"):
            need.add((name, 0))  # a far callee whose only callers are claims
    by_public = {r["public"]: r for r in reports}
    changed = bool(need)
    while changed:
        changed, sites = False, {}
        exact = [p for p in states if by_public[p].get("exact") and p not in conditional]
        for public in exact:
            for field in states[public]["far_fields"]:
                if field["key"] in need and field["equal"]:
                    sites.setdefault(field["key"], set()).add(field["insn"])
        for public in exact:
            lacking = sorted({f["key"] for f in states[public]["far_fields"]
                              if f["key"] in need and len(sites.get(f["key"], ())) < 2})
            if lacking:
                by_public[public].update(exact=False, state="REFUSED",
                                         reason="Far address lacks a second equal claimed site: " +
                                         ", ".join(f"{n}+{k}" for n, k in lacking))
                changed = True


def _data_tail(piece, own_targets, tables, start, addressed=()):
    """Rows for a claim whose code ends in a return/JMP before data the object addresses itself (e.g. a
    literal after the RET, `mov si, offset Lit`): the tail from the lowest own-segment field
    target T inside the claim is data when [0, T) decodes completely (around any tables) and
    ends in a return or JMP. The tail bytes are still compared exactly as ordinary bytes.
    `addressed` are the object offsets that fields of the object's other functions address (a signature
    between two procedures, used by the second). A jump-table entry names code, never such a tail."""
    cs, _ = _capstone()
    # own_targets: claim-relative field offset -> object offset it addresses (LEDATA + FIXUPP D).
    values = [value for at, value in own_targets.items() if not any(lo <= at < hi for lo, hi in tables)]
    targets = sorted({value - start for value in [*values, *addressed] if 0 < value - start < len(piece)})
    for t in targets:
        if any(lo < t < hi for lo, hi in tables) or any(at >= t for at in own_targets):
            continue
        try:
            rows = _decode(piece, [r for r in tables if r[1] <= t] + [(t, len(piece))])
        except ValueError:
            continue
        code = [i for i in rows if i.address < t]
        last = [i for i in code if bytes(i.bytes) != bytes((0x90,))][-1:] if code else []
        if last and (set(last[0].groups).intersection((cs.CS_GRP_RET, cs.CS_GRP_IRET)) or
                     last[0].mnemonic == "jmp"):
            return code
    return None


def _object_order(reports, states, code_fixes):
    """Relocation targets whose order across the object's exact claims differs from FIXUPP traversal.

    RTLink keeps raw FIXUPP order inside one (target, field) group of the output segment, across functions too, so one
    compilation of the original file must show the original order for every group (docs/far-call-binding.md)."""
    traversal = {f["segment_offset"]: i for i, f in enumerate(code_fixes)}
    groups = {}
    for report in reports:
        state = states.get(report["public"])
        if not report.get("exact") or state is None:
            continue
        index = {r["image_offset"]: r["index"] for r in state["relocations"]}
        for site in state.get("sites", ()):
            groups.setdefault((site["symbol"], site.get("field", "pointer32")), []).append(
                (traversal[state["start"] + site["offset"]], index[site["site"]]))
    return sorted({f"{name}:{field}" for (name, field), rows in groups.items()
                   if [i for _, i in sorted(rows)] != sorted(i for _, i in rows)})


def _code_tables(tables, reports, states, publics, actual, code_fixes, data_fixes, module, name, origin, space, window,
                 oracle):
    """Judge the claimed code tables of one MASM object (docs/acceptance.md "Code tables").

    A table claim is one whole region of unclaimed publics: it starts at the object's start or where an exact claim ends,
    and ends where an exact claim starts or the object ends (at most one zero byte that word-aligns what follows stays
    outside). Every byte equals the original; its only fields are own-segment offset16 words, equations in the witnessed
    CS frame that name an instruction of an exact claim or the region itself. The program must read it: an equal own-segment
    field of an exact claim, or a pointer in the object's placed data, addresses a byte of the region."""
    exact = [(r["object_offset"], r["object_offset"] + r["emitted_size"]) for r in reports if r.get("exact")]
    starts, ends = {lo for lo, _ in exact}, {hi for _, hi in exact}
    entries = {lo + i.address for r, (lo, _) in zip([r for r in reports if r.get("exact")], exact)
               for i in states[r["public"]]["rows"] or ()}
    readers = {own["addend"] & 0xFFFF for r in reports if r.get("exact") for own in states[r["public"]]["own"]}
    for fix in data_fixes:
        content = module.segments.get(fix["segment"]) or b""
        at, target = fix["segment_offset"], fix["target"]
        base = 0 if target.get("kind") == "segment" and target.get("name") == name else \
            publics.get(target.get("name")) if target.get("kind") == "external" else None
        if base is not None and fix["loc_type"] in (1, 3) and not fix["self_relative"]:
            readers.add((base + struct.unpack_from("<H", content, at)[0] + (fix["displacement"] or 0)) & 0xFFFF)
    found = []
    for table in tables:
        target, home, expected = get_table(table["target_id"], oracle)
        require(home.name == space.name and table["public"] in publics, "Code table is not in this object")
        start = publics[table["public"]]
        end, position = start + len(expected), origin + start
        require(space.position(target["segment"], target["offset"]) == position and end <= len(actual),
                "Code table does not share the object placement")
        require(start == 0 or start in ends, "Code table does not start where accepted code ends")
        follows = lambda at: at == len(actual) or at in starts
        require(follows(end) or (origin + end) % 2 and end < len(actual) and actual[end] == 0 and follows(end + 1),
                "Code table does not end where accepted code starts")
        require(not any(lo < end and start < hi for lo, hi in exact), "Code table overlaps a claim")
        marks = sorted([o for o in publics.values() if start <= o < end]) + [end]
        require(not any(hi - lo == 1 and actual[lo] == 0 for lo, hi in zip(marks, marks[1:])),
                "A single zero alignment byte is never part of a code table")
        require(not any(position - 1 <= r["image_offset"] < origin + end for r in space.relocations),
                "Code table overlaps original relocated words")
        require(window is not None and window[0] <= position and origin + end <= window[1],
                "Code table lies outside the witnessed original CS window")
        piece, occupied, equations = bytearray(actual[start:end]), set(), []
        for fix in (f for f in code_fixes if f["segment_offset"] < end and start < f["segment_offset"] + f["field_width"]):
            at = fix["segment_offset"] - start
            require(_own_segment(fix, name) and fix["field_width"] == 2 and 0 <= at and at + 2 <= len(piece) and
                    not occupied.intersection((at, at + 1)), "Unsupported field in a code table")
            addend = (struct.unpack_from("<H", piece, at)[0] + (fix["displacement"] or 0)) & 0xFFFF
            require(addend in entries or start <= addend < end,
                    "Code table word names no instruction of an accepted claim")
            value, observed = (origin - window[0] + addend) & 0xFFFF, struct.unpack_from("<H", expected, at)[0]
            require(value == observed, "Code table word differs from the original")
            equations.append({"offset": at, "kind": "own-segment offset16", "encoded_addend": addend,
                              "linked_value": value, "original_value": observed, "equal": True})
            piece[at:at + 2] = struct.pack("<H", value)
            occupied.update((at, at + 1))
        require(bytes(piece) == expected, "Code table differs from the original")
        used = sorted(a for a in readers if start <= a < end)
        require(used, "No accepted code or placed data reads the code table")
        found.append({"target_id": table["target_id"], "public": table["public"], "object_offset": start,
                      "size": len(expected), "fixups": len(equations), "read_at": used, "exact": True,
                      "state": "ASM_DATA_EXACT", "equations": equations})
    require(len({t["target_id"] for t in found}) == len(found), "Duplicate code table claim")
    return found


def check_group(obj_data, claims, oracle, *, binding=None, group_id=None, code_tables=()):
    """Judge every claim; never raises for a claim-level mismatch, only for object-level refusal."""
    module = OmfReader().read(obj_data, "candidate")
    placements = (binding or {}).get("placements", {})
    far_spec = (binding or {}).get("far_placements", {})
    segment, name, actual = code_segment(module, placed=(*placements, *far_spec))
    far_placements = _far_placements(module, far_spec, fixes(module), oracle)
    dgroup_members = {module.segment_defs[i - 1]["name"] for g in module.groups if g["name"] == "DGROUP"
                      for i in g["segments"] if 1 <= i <= len(module.segment_defs)}
    publics, data_publics = {}, _data_publics(module, placements, dgroup_members, name)
    for public in module.publics:
        if public["segment"] != name:
            continue  # a data public, checked by _data_publics
        require(public["name"] not in publics and public["name"] not in data_publics, "Duplicate public")
        require(0 <= public["offset"] < len(actual), "Public outside the initialized CODE segment")
        publics[public["name"]] = public["offset"]
    offsets = sorted(publics.values())
    require(len(set(offsets)) == len(offsets), "Two publics share one offset")
    require(offsets and offsets[0] == 0, "Code before the first public would be unaccounted for")
    require(claims and len({c["target_id"] for c in claims}) == len(claims) and
            len({c["public"] for c in claims}) == len(claims), "Claims must be unique")
    obligations = fixes(module)
    # Fixups inside a placed initialized DGROUP segment (near pointers in an initialized table)
    # are linker equations on that segment's bytes, judged by _check_placements; every other
    # fixup must lie in the CODE segment and is judged per claim.
    data_fixes = [f for f in obligations if f["segment"] != name]
    code_fixes = [f for f in obligations if f["segment"] == name]
    require(all(f["segment"] in placements for f in data_fixes),
            "Fixup in a data segment that has no DGROUP placement")
    fields = set()
    for fix in code_fixes:
        span = set(range(fix["segment_offset"], fix["segment_offset"] + fix["field_width"]))
        require(not fields.intersection(span) and max(span) < len(actual),
                "Fixup fields overlap or leave the CODE segment")
        fields.update(span)
    resolved, origin, space = [], None, None
    for claim in claims:
        require(claim["public"] in publics, f"Claimed public {claim['public']} is not emitted")
        target, target_space, expected = get_target(claim["target_id"], oracle)
        require(space is None or target_space.name == space.name, "Claims span several spaces")
        space = target_space
        position = space.position(target["segment"], target["offset"])
        start = publics[claim["public"]]
        require(origin is None or position - start == origin,
                "Claims do not share one object placement")
        origin = position - start
        resolved.append((claim, target, expected, start))
    require(0 <= origin and origin + len(actual) <= space.size, "Object placement escapes the space")
    code_index = next(i for i, d in enumerate(module.segment_defs, 1) if d["name"] == name)
    grouped = any(code_index in g["segments"] for g in module.groups)
    frame_rows = {claim["public"]: _frame_evidence(target, space, oracle, (origin, origin + len(actual)), grouped)
                  for claim, target, _, _ in resolved}
    frames = {row["frame"] for evidence, _ in frame_rows.values() for row in evidence}
    require(len(frames) <= 1, "Claims are entered through different original frames")
    window = None
    if frames:
        base = (next(iter(frames)) - space.link_segment) * 16
        window = (base, base + 0x10000)
    symbols, mode, far_symbols, near_symbols, span_aliases = None, None, {}, {}, []
    if binding is not None:
        require(binding["fixups"] == obligations, "Ordered symbolic fixup obligations changed")
        require(binding["declarations"] == declarations(module), "Bound object declarations changed")
        require(group_id is not None and binding["target_id"] == group_id, "Binding belongs to another group")
        hull = dict(space.address(origin), id=group_id, size=len(actual))
        # Far callees (other files) ground exactly as in the single-function far gate:
        # a reviewed direct entry plus independent relocated CALL FAR witnesses, all
        # outside the whole object. Near callees outside the object ground by an accepted
        # exact owner or an outside original near CALL. Data symbols use the DGROUP modes.
        # Unproven symbols (docs/acceptance.md "Code matches with unproven bindings"): their declared
        # value enters every equation, but nothing grounds it; a claim using one is a CODE_MATCH at
        # best, never CODE_EXACT.
        unproven = {n: s for n, s in binding["symbols"].items() if s.get("unproven")}
        for n, s in unproven.items():
            require(type(s["unproven"]) is str and s["unproven"].strip() and
                    (s.get("kind") == "dgroup-offset" and type(s.get("offset")) is int and not s.get("extent") or
                     s.get("kind") in ("far-code-entry", "overlay-code-entry") and
                     type(s.get("segment")) is int and type(s.get("offset")) is int),
                    f"Unsupported unproven binding symbol {n}")
            if s.get("kind") != "dgroup-offset":
                callee, _, _ = get_target(s["entry_target_id"], oracle)
                require((callee["segment"], callee["offset"]) == (s["segment"], s["offset"]),
                        f"Unproven far symbol {n} does not name its reviewed entry")
        far_symbols = {n: s for n, s in binding["symbols"].items() if s.get("kind") in FAR_KINDS}
        near_symbols = {n: near_ground(s, hull, oracle) for n, s in binding["symbols"].items()
                        if s.get("kind") == NEAR_KIND}
        provided = {n: s for n, s in binding["symbols"].items() if s.get("kind") == PUBLIC_KIND}
        data_only = {n: s for n, s in binding["symbols"].items()
                     if n not in far_symbols and n not in near_symbols and n not in provided}
        # Overlay owners too: the field equation depends only on the grounded 16:16 alias,
        # and its segment word is relocated by the owner's own overlay table (bijection below).
        for n, symbol in far_symbols.items():
            if n in unproven:
                # "Unproven" must be true: a far symbol the gate can ground may not be recorded as unproven.
                try:
                    far_ground({k: v for k, v in symbol.items() if k != "unproven"}, hull, oracle,
                               claimed=[(origin + start, origin + start + len(expected))
                                        for _, _, expected, start in resolved])
                except ValueError:
                    continue
                raise ValueError(f"Unproven far symbol {n} is provable: bind it as proven")
            far_ground(symbol, hull, oracle,
                       claimed=[(origin + start, origin + start + len(expected)) for _, _, expected, start in resolved])
        if data_only or provided:
            claimed = [(origin + start, origin + start + len(expected)) for _, _, expected, start in resolved]
            symbols = ground({**binding, "symbols": {n: s for n, s in data_only.items() if n not in unproven}},
                             hull, oracle, claimed=claimed if binding["mode"] == OPERAND_MODE else None)
            require(not unproven or binding["mode"] == OPERAND_MODE, "Unproven data symbols need the v4 mode")
            symbols = dict(symbols, **{n: s for n, s in data_only.items() if n in unproven})
            mode = binding["mode"]
            require(not provided or mode == OPERAND_MODE, "Provider data publics need the v4 operand mode")
            symbols = dict(symbols, **{n: _provider_public(n, s, oracle, group_id, set(publics) | set(data_publics))
                                       for n, s in provided.items()})
            if mode == OPERAND_MODE:
                span_aliases = _check_unplaced(module, placements, symbols)
        elif "frame" in binding:
            # Verify the DGROUP frame witness even without data symbols (DGROUP base fields).
            ground({**binding, "mode": OPERAND_MODE, "symbols": {}}, hull, oracle)
        else:
            require(binding["mode"] in ("external-far-call-v1",) + DATA_MODES, "Unsupported group binding mode")
            symbols, mode = {}, binding["mode"]

    # Member extents: the same evidence kinds as a symbol's aggregate extent, at S+h.
    for symbol in ((binding or {}).get("symbols", {}).values() if binding and binding.get("mode") == OPERAND_MODE else ()):
        for member in symbol.get("members", []) if symbol.get("kind") == "dgroup-offset" else ():
            if "extent" in member:
                ground({**binding, "symbols": {"MEMBER": {
                    "kind": "dgroup-offset", "group": "DGROUP", "offset": (symbol["offset"] + member["offset"]) & 0xFFFF,
                    "witnesses": [], "extent": member["extent"]}}}, hull, oracle,
                    claimed=[(origin + start, origin + start + len(expected)) for _, _, expected, start in resolved])

    # Independent witnesses of addresses inside the object's own placed segments: the operand equals P + A.
    placed_witnessed, placed_extents = set(), []
    for row in (binding or {}).get("placed_witnesses", []):
        require(set(row) in ({"segment", "addend", "witnesses"}, {"segment", "addend", "squeeze"},
                             {"segment", "addend", "extent"}) and
                row["segment"] in placements and type(row["addend"]) is int and 0 <= row["addend"],
                "Unsupported placed witness")
        key = (row["segment"], row["addend"])
        address = (placements[row["segment"]] + row["addend"]) & 0xFFFF
        extents = [(origin + start, origin + start + len(expected)) for _, _, expected, start in resolved]

        def proven(symbols):
            ground({**binding, "mode": OPERAND_MODE, "symbols": symbols}, hull, oracle, claimed=extents)
        v4 = {"kind": "dgroup-offset", "group": "DGROUP"}
        if "squeeze" in row:
            # A bounded index proves N bytes at P+A; the object below ends at P+A and the next address above is
            # P+A+N, both independently witnessed. No other place holds N bytes between them.
            from binding import index_extent, reachable_from_entry
            s = row["squeeze"]
            at, raw = s["index"]["image_offset"], bytes.fromhex(s["index"]["bytes_hex"])
            ispace = oracle.spaces[s["index"]["space"]]
            require(set(s) == {"index", "below", "above"} and ispace.data[at:at + len(raw)] == raw and
                    at in reachable_from_entry(oracle, s["index"]["entry"]), "Squeeze index is not reached original code")
            count = index_extent(raw, address)
            require(count and s["below"]["witnesses"] and s["above"] and
                    s["below"]["offset"] + s["below"]["extent"]["length"] == address, "Squeeze leaves another position")
            proven({"BELOW": dict(v4, **s["below"]), "ABOVE": dict(v4, offset=address + count, witnesses=s["above"])})
        elif "extent" in row:
            # The object that starts at P+A; its base still needs two equal claimed sites or its own row.
            proven({"PLACED": dict(v4, offset=address, witnesses=[], extent=row["extent"])})
            placed_extents.append((*key, row["extent"]["length"]))
            continue
        else:
            require(row["witnesses"], "Placed witness without witnesses")
            proven({"PLACED": dict(v4, offset=address, witnesses=row["witnesses"])})
        placed_witnessed.add(key)

    addressed = {f["segment_offset"]: (struct.unpack_from("<H", actual, f["segment_offset"])[0] +
                                       (f["displacement"] or 0)) & 0xFFFF
                 for f in code_fixes if _own_segment(f, name)}
    # Pass 1: extent, decoding, near equations. Pass 2: segment safety. Pass 3: data.
    states, reports, placed_uses, used_near, far_used = {}, [], {}, set(), set()
    for claim, target, expected, start in resolved:
        later = [o for o in offsets if o > start]
        end = later[0] if later else len(actual)
        report = {"target_id": claim["target_id"], "public": claim["public"], "object_offset": start,
                  "expected_size": len(expected), "emitted_size": end - start,
                  "expected_sha256": sha(expected), "emitted_sha256": sha(actual[start:end])}
        evidence, unusable = frame_rows[claim["public"]]
        if space.name != "root":
            report.update(frame_evidence=evidence, frame_evidence_refused=unusable)
        reports.append(report)
        try:
            piece = actual[start:end]
            require(len(piece) == len(expected), "Claim extent differs from the reviewed target; trimming forbidden")
            position = origin + start
            mine = [f for f in code_fixes if start <= f["segment_offset"] < end]
            require(all(f["segment_offset"] + f["field_width"] <= end for f in mine) and
                    not any(f["segment_offset"] < start < f["segment_offset"] + f["field_width"]
                            for f in code_fixes), "Fixup field crosses the claim boundary")
            own_targets = {f["segment_offset"] - start: (struct.unpack_from("<H", piece, f["segment_offset"] - start)[0]
                                                         + (f["displacement"] or 0)) & 0xFFFF
                           for f in mine if _own_segment(f, name)}
            tables = _tables(own_targets, start)
            try:
                inline = _inline_data(piece, own_targets, tables, start)
                rows = _decode(piece, sorted([*tables, *inline])) if tables or inline else instructions(piece)
            except ValueError:
                rows = _data_tail(piece, own_targets, tables, start,
                                  [a for at, a in addressed.items() if not start <= at < end]) if mine else None
                require(rows is not None or not mine, "Fixup-bearing claim does not decode completely")
            state = {"start": start, "piece": piece, "expected": expected, "rows": rows,
                     "occupied": set(), "differences": [], "equations": [], "calls": {}, "data": [],
                     "near": [], "far": [], "own": [], "tables": tables, "group_bases": [], "own_bases": [], "own_base_labels": {}, "far_bases": {}, "v4": [], "far_fields": [], "placed": [],
                     "proven_jumps": set(),
                     "fixups": len(mine), "frames": {row["frame"] for row in evidence},
                     "names": {f["target"].get("name") for f in mine if f["target"].get("kind") == "external"},
                     "report": report, "position": position,
                     "relocations": [r for r in space.relocations
                                     if position-1 <= r["image_offset"] < position+len(expected)]}
            starts = {i.address for i in rows} if rows else set()
            for fix in mine:
                at = fix["segment_offset"] - start
                if _own_segment(fix, name):
                    in_table = any(lo <= at < hi for lo, hi in tables)
                    # Any decoded disp16/imm16 field qualifies here, including the indirect
                    # `jmp cs:[bx+T]` displacement that selects the jump table.
                    require(in_table or any((i.disp_size == 2 and i.address + i.disp_offset == at) or
                                            (i.imm_size == 2 and i.address + i.imm_offset == at)
                                            for i in rows),
                            "Own-segment field is neither a jump-table word nor an operand field")
                    # MASM may carry the offset in the FIXUPP displacement: the linker adds D + A.
                    addend = (struct.unpack_from("<H", piece, at)[0] + (fix["displacement"] or 0)) & 0xFFFF
                    if in_table:
                        # A table entry must point at an instruction start inside this claim.
                        require(start <= addend < end and (addend - start) in starts,
                                "Jump-table entry does not target an instruction of the claim")
                    state["own"].append({"offset": at, "addend": addend})
                    state["occupied"].update((at, at+1))
                elif (not fix["self_relative"] and fix["loc_type"] in (1, 5) and fix["field_width"] == 2 and
                      fix["target"].get("kind") == "external" and fix["target"].get("name") in publics and
                      fix["frame"] == {"kind": "target_frame", "target": fix["target"]} and
                      any(i.imm_size == 2 and i.address + i.imm_offset == at for i in rows or ())):
                    # `mov ax, offset Func` / `push offset Func` naming a public of this object (a
                    # callback address, an immediate only: a DS memory operand naming code stays
                    # refused below): the own-segment offset16 equation, addend = Func + A + D.
                    addend = (publics[fix["target"]["name"]] + struct.unpack_from("<H", piece, at)[0] +
                              (fix["displacement"] or 0)) & 0xFFFF
                    state["own"].append({"offset": at, "addend": addend})
                    state["occupied"].update((at, at+1))
                elif (not fix["self_relative"] and fix["field_width"] == 2 and fix["loc_type"] in (1, 2) and
                      fix["target"].get("kind") == "external" and fix["target"].get("name") in near_symbols and
                      fix["target"]["name"] not in publics):
                    # MASM `mov ax, OFFSET Near` / `mov ax, SEG Near` with `EXTRN Near:NEAR`: both framed by this
                    # code segment, so the offset is the grounded entry's within the CS frame and the segment is
                    # that frame's paragraph (checked below, as for the object's own code).
                    require({k: fix["frame"].get(k) for k in ("kind", "name")} == {"kind": "segment", "name": name} and
                            fix["displacement"] is None and piece[at:at+2] == bytes(2) and
                            any(i.imm_size == 2 and i.address + i.imm_offset == at for i in rows or ()),
                            "Unsupported near-code address field")
                    used_near.add(fix["target"]["name"])
                    if fix["loc_type"] == 1:
                        callee_at = near_symbols[fix["target"]["name"]]["position"]
                        state["own"].append({"offset": at, "addend": callee_at - origin, "target": callee_at})
                    else:
                        state["own_bases"].append(at)
                        state["own_base_labels"][at] = fix["target"]["name"]
                    state["occupied"].update((at, at+1))
                elif fix["self_relative"]:
                    kind, dest, (branch, insn_at, push_cs) = _self_relative(
                        fix, name, publics, near_symbols, piece, at, rows, start, end)
                    # Linear (space-relative) positions: value = S - (P + 2) mod 65536.
                    field = origin + fix["segment_offset"]
                    if kind == "internal":
                        callee_at = origin + dest
                    elif kind == "public":
                        callee_at = origin + publics[dest]
                    else:
                        callee_at = near_symbols[dest]["position"]
                        used_near.add(dest)
                    value = (callee_at - (field + 2)) & 0xFFFF
                    observed = struct.unpack_from("<H", expected, at)[0]
                    label = {"internal": "own-segment rel16", "public": "same-object near16",
                             "external": "external near16"}[kind]
                    row = {"offset": at, "kind": label, "instruction": branch, "push_cs": push_cs,
                           "linked_value": value, "original_value": observed, "equal": value == observed}
                    if kind == "internal":
                        row["destination"] = dest - start
                        state["proven_jumps"].add(insn_at)
                    else:
                        row["symbol"] = dest
                        # Runtime meaning needs CS: the whole call (with its PUSH CS) and the
                        # callee must lie in one witnessed CS window (checked below).
                        state["near"].append({"pair_start": origin + start + insn_at - (1 if push_cs else 0),
                                              "field_end": field + 2,
                                              "callee": dest if kind == "public" else None,
                                              "callee_at": callee_at, "equal": value == observed})
                        # A same-object callee must itself be proven safe; an external near
                        # callee is never assumed to preserve segment context.
                        if branch == "jmp":
                            state["proven_jumps"].add(insn_at)  # a tail jump: control ends here
                        else:
                            state["calls"][insn_at] = dest if kind == "public" else EXTERNAL_NEAR
                    state["equations"].append(row)
                    if value != observed:
                        state["differences"].append(at)
                    state["occupied"].update((at, at+1))
                elif fix["target"].get("name") in far_symbols:
                    require(fix["target"]["name"] not in publics,
                            "Far fixup target resolves to a CODE public of this object")
                    state["far"].append(dict(fix, segment_offset=at))
                    if far_symbols[fix["target"]["name"]].get("kind") not in ("segment-base", "far-data") and                             fix["loc_type"] == 3:
                        state["calls"][at - 1] = None  # a far callee, not a claim
                elif fix["target"].get("kind") == "segment" and fix["target"].get("name") in far_placements:
                    # The object's own far data at paragraph N: the offset half is A, the segment half N.
                    require(fix["loc_type"] in (1, 2, 5) and not fix["self_relative"] and fix["field_width"] == 2 and
                            fix["displacement"] is None and
                            fix["frame"] == {"kind": "target_frame", "target": fix["target"]},
                            "Unsupported own far data fixup shape")
                    require(any(operand_field_of(i, at, candidate=True) for i in rows or ()),
                            "Own far data fixup is not the address field of one decoded instruction")
                    seg_name = fix["target"]["name"]
                    encoded = struct.unpack_from("<H", piece, at)[0]
                    if fix["loc_type"] == 2:
                        require(encoded == 0, "Only zero encoded segment addends are proven")
                        value = far_placements[seg_name]["paragraph"]
                        state["far_bases"][at] = seg_name
                    else:
                        require(encoded < far_placements[seg_name]["length"], "Own far data offset leaves the segment")
                        value = encoded
                    observed = struct.unpack_from("<H", expected, at)[0]
                    state["equations"].append({"offset": at, "kind": "own far data", "segment": seg_name,
                                               "encoded_addend": encoded, "linked_value": value,
                                               "original_value": observed, "equal": value == observed})
                    if value != observed:
                        state["differences"].append(at)
                    state["occupied"].update((at, at+1))
                    far_used.add(seg_name)
                elif (fix["target"].get("kind") == "segment" and fix["target"].get("name") in placements and
                      fix["loc_type"] == 1 and not fix["self_relative"] and fix["field_width"] == 2):
                    # A field addressing this object's own placed DGROUP segment: P + A. Only
                    # the DGROUP frame (F1, MSC and MASM `ASSUME DS:DGROUP`) adds P; a segment
                    # or target frame would write A alone, so it is refused.
                    require(fix["frame"].get("kind") == "group" and fix["frame"].get("name") == "DGROUP" and
                            fix["target"]["name"] in dgroup_members,
                            "Placed-data fixup must use the DGROUP frame of a DGROUP member segment")
                    require(any(operand_field_of(i, at, candidate=True) for i in rows),
                            "Placed-data fixup is not the address field of one decoded instruction")
                    seg_name = fix["target"]["name"]
                    # MASM may carry the offset in the FIXUPP displacement (T0/T4 with D) instead of
                    # the LEDATA bytes; the linker adds both: P + D + A.
                    addend = (struct.unpack_from("<H", piece, at)[0] + (fix["displacement"] or 0)) & 0xFFFF
                    value = (placements[seg_name] + addend) & 0xFFFF
                    observed = struct.unpack_from("<H", expected, at)[0]
                    state["equations"].append({"offset": at, "kind": "placed data", "segment": seg_name,
                                               "encoded_addend": addend, "placement": placements[seg_name],
                                               "linked_value": value, "original_value": observed,
                                               "equal": value == observed})
                    if value != observed:
                        state["differences"].append(at)
                    state["occupied"].update((at, at+1))
                    if value == observed:
                        placed_uses.setdefault(seg_name, set()).add(addend)
                    insn = next(i for i in rows if i.address <= at < i.address + i.size)
                    state["placed"].append({"key": (seg_name, addend), "equal": value == observed,
                                            "insn": state["position"] + insn.address, "offset": at,
                                            "pointer": pointer_extent(expected[insn.address:insn.address + insn.size],
                                                                      observed) == 4})
                elif (fix["loc_type"] == 2 and not fix["self_relative"] and fix["field_width"] == 2 and
                      ((fix["target"].get("kind") == "group" and fix["target"].get("name") == "DGROUP") or
                       (fix["target"].get("kind") == "segment" and fix["target"].get("name") in dgroup_members and
                        {k: fix["frame"].get(k) for k in ("kind", "name")} == {"kind": "group", "name": "DGROUP"}))):
                    # `mov ax, DGROUP` or `mov ax, seg _DATA` framed by DGROUP: both link to the DGROUP
                    # paragraph (the frame decides a base fixup's value).
                    # `mov ax, DGROUP`: the DGROUP paragraph, grounded by the binding's startup
                    # DS-load frame witness; relocated in MZ at the field itself.
                    require(binding is not None and "frame" in binding and fix["displacement"] is None,
                            "DGROUP base needs a binding with a grounded DGROUP frame")
                    require(piece[at:at+2] == bytes(2), "Only zero encoded DGROUP base addends are proven")
                    # The runtime DGROUP paragraph: the grounded `dgroup_segment` when the binding has
                    # one (the C runtime reloads DS with it before main), else the startup DS frame.
                    if "dgroup_segment" in binding:
                        from far_binding import _ground_segment
                        seg_spec = binding["dgroup_segment"]
                        _ground_segment({"segment": seg_spec["segment"], "witnesses": seg_spec["witnesses"]},
                                        {"space": "root", "segment": 0, "offset": 0, "size": 0}, oracle)
                        value = seg_spec["segment"]
                    else:
                        value = binding["frame"]["segment"]
                    observed = struct.unpack_from("<H", expected, at)[0]
                    state["equations"].append({"offset": at, "kind": "DGROUP base", "linked_segment": value,
                                               "original_segment": observed, "equal": value == observed})
                    if value != observed:
                        state["differences"].append(at)
                    state["occupied"].update((at, at+1))
                    state["group_bases"].append(at)
                elif (fix["loc_type"] == 2 and not fix["self_relative"] and fix["field_width"] == 2 and
                      fix["displacement"] is None and
                      ((fix["target"].get("kind") == "external" and fix["target"].get("name") in publics) or
                       {k: fix["target"].get(k) for k in ("kind", "name")} == {"kind": "segment", "name": name}) and
                      (fix["frame"].get("kind") == "target_frame" or
                       {k: fix["frame"].get(k) for k in ("kind", "name")} == {"kind": "segment", "name": name})):
                    # `mov ax, SEG Func` naming this object's own code: the CS frame paragraph of the
                    # witnessed window (checked once the claim's frame is proven below).
                    require(piece[at:at+2] == bytes(2), "Only zero encoded own-segment base addends are proven")
                    state["own_bases"].append(at)
                    # RTLink buckets relocations by target identity: an EXTDEF resolving to a public
                    # of this object is its own bucket; the segment itself (T4) is another.
                    state["own_base_labels"][at] = (fix["target"]["name"] if fix["target"].get("kind") == "external"
                                                    else name)
                    state["occupied"].update((at, at+1))
                else:
                    require(fix["target"].get("name") not in publics,
                            "Data fixup target resolves to a CODE public of this object")
                    require(fix["target"].get("name") not in data_publics,
                            "Data fixup target resolves to a data public of this object")
                    state["data"].append(dict(fix, segment_offset=at))
            require(not state["relocations"] or state["far"] or state["group_bases"] or state["own_bases"] or
                    state["far_bases"],
                    "Original MZ relocations need far CALL fixups in the claim")
            states[claim["public"]] = state
        except ValueError as error:
            report.update(exact=False, state="REFUSED", reason=str(error))

    # Original CS: a claim runs in the witnessed frame if a relocated CALL FAR names
    # it directly, or a claim already proven so reaches it by an equal near call whose
    # whole PUSH CS; CALL pair and callee lie inside that frame's 64K window.
    def in_window(near):
        return (window is not None and window[0] <= near["pair_start"] and near["field_end"] <= window[1]
                and window[0] <= near["callee_at"] < window[1])

    cs_proven = {p for p, s in states.items() if s["frames"]}
    # Root code entered only through CS-relative words (docs/acceptance.md "Solved CS frames"):
    # the original own-segment words fix one frame, which must equal any witnessed frame.
    claimed_spans = [(s["start"], s["start"] + len(s["piece"])) for s in states.values()]
    table_words = []
    for fix in code_fixes:
        at = fix["segment_offset"]
        if not _own_segment(fix, name) or any(lo <= at < hi for lo, hi in claimed_spans) or \
                any(lo <= at < hi for lo, hi in ((r["object_offset"], r["object_offset"] + r["emitted_size"])
                                                 for r in reports)):
            continue
        position = origin + at
        if any(position - 1 <= r["image_offset"] <= position + 1 for r in space.relocations):
            continue
        addend = (struct.unpack_from("<H", actual, at)[0] + (fix["displacement"] or 0)) & 0xFFFF
        table_words.append((addend, at, struct.unpack_from("<H", space.data, position)[0]))
    solution = _solved_frame(states, cs_proven, table_words, space, oracle, origin, publics)
    if solution is not None and (window is None or window[0] == solution[0]):
        base, solved, entered, count = solution
        # Only claims that need a frame take it; a frame-invariant claim keeps its weaker class, and
        # a group whose claims need no frame keeps no frame.
        needing = [p for p in sorted(solved | entered)
                   if (states[p]["near"] or states[p]["own"] or states[p]["own_bases"]) and not
                   (not states[p]["own"] and not states[p]["own_bases"] and _frame_invariant(states[p], space, oracle))]
        if needing and window is None:
            window = (base, base + 0x10000)
            frames = {base // 16 + space.link_segment}
        for p in needing:
            cs_proven.add(p)
            states[p]["report"]["cs_frame"] = (f"solved from {count} own-segment words" +
                                               (", entered through a table word" if p in entered else ""))
    changed = True
    while changed:
        changed = False
        for public in list(cs_proven):
            for near in states[public]["near"]:
                if near["equal"] and in_window(near) and near["callee"] in states and \
                        near["callee"] not in cs_proven:
                    cs_proven.add(near["callee"])
                    changed = True
    for public, state in list(states.items()):
        if state["own"] and public in cs_proven and window is not None:
            # Own-segment word = segment-relative offset in the witnessed frame: origin - base + A.
            for own in state["own"]:
                value = (origin - window[0] + own["addend"]) & 0xFFFF
                observed = struct.unpack_from("<H", state["expected"], own["offset"])[0]
                state["equations"].append({"offset": own["offset"], "kind": "own-segment offset16",
                                           "encoded_addend": own["addend"], "linked_value": value,
                                           "original_value": observed, "equal": value == observed})
                if value != observed:
                    state["differences"].append(own["offset"])
        if state["own_bases"] and public in cs_proven and window is not None:
            # Own-segment base = the witnessed CS frame paragraph itself.
            for at in state["own_bases"]:
                value = next(iter(frames))
                observed = struct.unpack_from("<H", state["expected"], at)[0]
                state["equations"].append({"offset": at, "kind": "own-segment base", "linked_segment": value,
                                           "original_segment": observed, "equal": value == observed})
                if value != observed:
                    state["differences"].append(at)
        if not state["near"] and not state["own"] and not state["own_bases"]:
            continue
        position = state["position"]
        if (public not in cs_proven and space.name == "root" and not state["own"] and
                not state["own_bases"] and _frame_invariant(state, space, oracle)):
            # Weaker class, recorded: no frame names this claim, but every frame the original
            # relocations store whose window holds the whole claim also holds every callee,
            # so each near call reaches the same code under any of them.
            state["report"]["cs_frame"] = "frame-invariant near calls"
            continue
        reason = ("Near call or own-segment word lacks an independently witnessed original frame"
                  if public not in cs_proven else
                  "Near call leaves the witnessed original CS window"
                  if not all(in_window(n) for n in state["near"]) else
                  "Own-segment word lies outside the witnessed original CS window"
                  if state["own"] and not (window[0] <= position and
                                           position + len(state["piece"]) <= window[1] and
                                           all(window[0] <= o.get("target", position) < window[1]
                                               for o in state["own"])) else None)
        if reason:
            state["report"].update(exact=False, state="REFUSED", reason=reason)
            del states[public]

    # A claim preserves DS/ES/SS only if its own code does, control cannot leave it
    # except by return or an allowed call, and every call goes to a claim that does too.
    # Unclaimed drafts are never assumed safe.
    safe, changed = set(), True
    while changed:
        changed = False
        for public, state in states.items():
            if public in safe or state["rows"] is None:
                continue
            # Far callees in other files keep DS/SS per the MSC far-call ABI, as the
            # single-function far gate also assumes; drafts and unproved claims do not.
            allowed = {at for at, callee in state["calls"].items() if callee is None or callee in safe}
            try:
                preserve_segments(state["rows"], allowed, es_ds=mode == IMMEDIATE_MODE)
                _contained(state["rows"], len(state["piece"]), state["proven_jumps"])
            except ValueError:
                continue
            safe.add(public)
            changed = True

    used_symbols, used_far = set(), set()
    for report in reports:
        state = states.get(report["public"])
        if state is None:
            continue
        try:
            relocation_proof = {}
            if state["far"]:
                sites = []
                by_address = {i.address: i for i in state["rows"]}
                for fix in state["far"]:
                    at, ref = fix["segment_offset"], fix["target"]
                    symbol = far_symbols[ref["name"]]
                    # LOC5 (loader-resolved offset16) writes the same value as LOC1 here.
                    # A far code pointer taken in halves (`mov ax,offset f; mov dx,seg f`, a callback argument):
                    # the linker writes the grounded entry's offset and segment (2026-11-23).
                    split = symbol.get("kind") in ("far-code-entry", "overlay-code-entry")
                    if (split or symbol.get("kind") == "far-data") and fix["loc_type"] in (1, 5) and                             not fix["self_relative"]:
                        # Offset half of a far data or code pointer: O within the target's own segment.
                        same_ext = {k: fix["frame"].get(k) for k in ("kind", "index", "name")} ==                             {"kind": "external", "index": ref.get("index"), "name": ref.get("name")}
                        require(fix["field_width"] == 2 and ref["kind"] == "external" and fix["displacement"] is None and
                                (fix["frame"] == {"kind": "target_frame", "target": ref} or same_ext),
                                "Unsupported far data offset fixup shape")
                        addend = struct.unpack_from("<H", state["piece"], at)[0]
                        require(addend == 0 or addend in {m["offset"] for m in symbol.get("members", [])},
                                "Far data addends must be zero or independently witnessed members")
                        linked = (symbol["offset"] + addend) & 0xFFFF
                        observed = struct.unpack_from("<H", state["expected"], at)[0]
                        state["equations"].append({"offset": at, "kind": "far-data offset", "symbol": ref["name"],
                                                   "encoded_addend": addend, "linked_offset": linked,
                                                   "original_offset": observed, "equal": linked == observed})
                        insn = next(i for i in state["rows"] if i.address <= at < i.address + i.size)
                        state["far_fields"].append({"key": (ref["name"], addend), "equal": linked == observed,
                                                    "insn": state["position"] + insn.address})
                        if linked != observed:
                            state["differences"].append(at)
                        state["occupied"].update(range(at, at+2))
                        used_far.add(ref["name"])
                        continue
                    if (split or symbol.get("kind") in ("segment-base", "far-data")) and fix["loc_type"] == 2:
                        # LOC2 base16 of an external far segment (`mov ax, seg Table`): the
                        # linker writes that segment's paragraph, relocated in MZ at the field.
                        # F5, or F2 naming the same external (MASM `mov ax, SEG X`): X's own frame.
                        same_external = {k: fix["frame"].get(k) for k in ("kind", "index", "name")} ==                             {"kind": "external", "index": ref.get("index"), "name": ref.get("name")}
                        require(fix["loc_type"] == 2 and fix["field_width"] == 2 and not fix["self_relative"] and
                                ref["kind"] == "external" and fix["displacement"] is None and
                                (fix["frame"] == {"kind": "target_frame", "target": ref} or same_external),
                                "Unsupported segment-base fixup shape")
                        require(state["piece"][at:at+2] == bytes(2), "Only zero encoded segment addends are proven")
                        observed = struct.unpack_from("<H", state["expected"], at)[0]
                        state["equations"].append({"offset": at, "kind": "segment-base", "symbol": ref["name"],
                                                   "linked_segment": symbol["segment"], "original_segment": observed,
                                                   "equal": symbol["segment"] == observed})
                        if symbol["segment"] != observed:
                            state["differences"].append(at)
                        state["occupied"].update(range(at, at+2))
                        sites.append({"site": state["position"] + at, "offset": at, "symbol": ref["name"], "field": "base16"})
                        used_far.add(ref["name"])
                        continue
                    # F5 (target frame, MSC) or F2 naming the same external as the target (MASM
                    # `call far ptr X`): both frame the pointer by X's own segment.
                    same_external = {k: fix["frame"].get(k) for k in ("kind", "index", "name")} ==                         {"kind": "external", "index": ref.get("index"), "name": ref.get("name")}
                    require(fix["loc_type"] == 3 and fix["field_width"] == 4 and not fix["self_relative"] and
                            ref["kind"] == "external" and ref["method"] == 6 and fix["displacement"] is None and
                            (fix["frame"] == {"kind": "target_frame", "target": ref} or same_external),
                            "Unsupported far CALL fixup equation/frame/displacement")
                    insn = by_address.get(at - 1)
                    # CALL FAR (9A) or a far tail JMP (EA): the same pointer32 equation; a JMP never returns.
                    require(insn is not None and insn.size == 5 and insn.bytes[0] in (0x9a, 0xea),
                            "Far fixup is not a complete unprefixed 9A CALL or EA JMP operand")
                    require(state["piece"][at:at+4] == bytes(4), "Only zero encoded far addends are proven")
                    value = (symbol["offset"], symbol["segment"])
                    observed = struct.unpack_from("<HH", state["expected"], at)
                    state["equations"].append({"offset": at, "kind": "far-call", "symbol": ref["name"],
                                               "linked_offset": value[0], "linked_segment": value[1],
                                               "original_offset": observed[0], "original_segment": observed[1],
                                               "equal": value == observed})
                    if value != observed:
                        state["differences"].append(at)
                    state["occupied"].update(range(at, at+4))
                    sites.append({"site": state["position"] + at + 2, "offset": at, "symbol": ref["name"], "field": "pointer32"})
                    state["far_fields"].append({"key": (ref["name"], 0), "equal": value == observed,
                                                "insn": state["position"] + insn.address})
                    used_far.add(ref["name"])
                sites += [{"site": state["position"] + g, "offset": g, "symbol": "DGROUP", "field": "base16"} for g in state["group_bases"]]
                sites += [{"site": state["position"] + g, "offset": g, "symbol": state["own_base_labels"][g], "field": "base16"}
                          for g in state["own_bases"]]
                sites += [{"site": state["position"] + g, "offset": g, "symbol": seg, "field": "base16"}
                          for g, seg in state["far_bases"].items()]
                relocation_proof = relocation_order(state["relocations"], sites,
                                                    [r["index"] for r in state["relocations"]])
                state["sites"] = sites
            if (state["group_bases"] or state["own_bases"] or state["far_bases"]) and not state["far"]:
                state["sites"] = sites = (
                    [{"site": state["position"] + g, "offset": g, "symbol": "DGROUP", "field": "base16"} for g in state["group_bases"]] +
                    [{"site": state["position"] + g, "offset": g, "symbol": state["own_base_labels"][g], "field": "base16"}
                          for g in state["own_bases"]] +
                    [{"site": state["position"] + g, "offset": g, "symbol": seg, "field": "base16"}
                     for g, seg in state["far_bases"].items()])
                relocation_proof = relocation_order(state["relocations"], sites,
                                                    [r["index"] for r in state["relocations"]])
            if state["data"]:
                require(symbols is not None, "DGROUP fixups require a grounded group binding")
                missing = sorted({f["target"].get("name") for f in state["data"]} - set(symbols))
                require(not missing, "DGROUP fixup targets lack grounded binding symbols: " + ", ".join(map(str, missing)))
                # v4 proves offset bytes only and claims no DS association, so it needs no
                # segment-context proof; the older modes keep theirs.
                require(mode == OPERAND_MODE or report["public"] in safe,
                        "DGROUP access after a call into code not proven to preserve segment context")
                allowed = {at for at, callee in state["calls"].items() if callee is None or callee in safe}
                data_context(module, state["rows"], allowed, mode=mode, placed=tuple(placements))
                found, unequal = data_equations(state["data"], symbols, name, state["piece"], state["expected"],
                                                state["rows"], mode, state["occupied"])
                state["equations"] += [dict(e, kind="DGROUP offset16") for e in found]
                state["differences"] += unequal
                if mode == OPERAND_MODE:
                    for e in found:
                        insn = next(i for i in state["rows"] if i.address <= e["offset"] < i.address + i.size)
                        state["v4"].append({"key": (e["symbol"], e["encoded_addend"]), "equal": e["equal"],
                                            "insn": state["position"] + insn.address, "offset": e["offset"]})
                used_symbols.update(f["target"]["name"] for f in state["data"])
            piece, expected, occupied = state["piece"], state["expected"], state["occupied"]
            differences = state["differences"] + [i for i in range(len(piece))
                                                  if i not in occupied and piece[i] != expected[i]]
            report.update(exact=not differences, state="CODE_EXACT" if not differences else "CANDIDATE_C",
                          first_difference=min(differences, default=None),
                          mismatch_count=len(differences), fixups=state["fixups"],
                          relocations=len(state["relocations"]),
                          covered_relocation_indices=[r["index"] for r in state["relocations"]],
                          equations=state["equations"], ordinary_bytes_compared=len(piece) - len(occupied),
                          **{k: v for k, v in relocation_proof.items()
                             if k in ("relocation_order", "relocation_order_debt", "relocation_groups")})
        except ValueError as error:
            report.update(exact=False, state="REFUSED", reason=str(error))
    if mode == OPERAND_MODE and binding is not None:
        _check_provider_aliases(symbols, states)
        unproven_keys = {(n, m["offset"]) for n, s in binding["symbols"].items() for m in s.get("members", [])
                         if m.get("unproven")}
        _internal_support(binding["symbols"], states, reports,
                          {p for p, s in states.items()
                           if s["names"] & set(unproven) or any(f["key"] in unproven_keys for f in s["v4"])})
    if binding is not None:
        unproven_far = {(n, m["offset"]) for n, s in far_symbols.items() for m in s.get("members", []) if m.get("unproven")}
        _far_consensus(far_symbols, states, reports,
                       {p for p, s in states.items() if s["names"] & set(unproven) or
                        any(f["key"] in unproven_far for f in s["far_fields"])})
    # A refused claim never evaluated its data fields; report it instead of masking the reason.
    # Near pointers in placed initialized data use grounded DGROUP symbols too (_linked_data).
    used_symbols |= {f["target"].get("name") for f in data_fixes
                     if f["loc_type"] in (1, 5) and f["target"].get("kind") == "external" and
                     f["target"].get("name") in (symbols or {})}
    if symbols is not None and not any(r["state"] == "REFUSED" for r in reports):
        require(set(symbols) == used_symbols, "Missing or unused grounded data symbol")
        used_far |= {f["target"].get("name") for f in data_fixes
                     if f["loc_type"] in (2, 3) and f["target"].get("kind") == "external" and
                     f["target"].get("name") not in publics}
        require(set(far_symbols) == used_far, "Missing or unused grounded far symbol")
    if not any(r["state"] == "REFUSED" for r in reports):
        require(set(near_symbols) == used_near, "Missing or unused grounded near-code entry")
        require(set(far_placements) == far_used, "Own far data that no claim addresses")
    placement_report = _check_placements(module, placements, placed_uses, binding, space, oracle,
                                         data_fixes, far_symbols, symbols, (origin, origin + len(actual)),
                                         (name, origin - window[0], len(actual), next(iter(frames)),
                                          {p["name"]: p["offset"] for p in module.publics if p["segment"] == name})
                                         if frames and window is not None else None)
    _placed_support(placement_report, states, reports, placed_witnessed, placed_extents)
    _bracket_located((binding or {}).get("brackets", {}), states, reports)
    table_report = _code_tables(code_tables, reports, states, publics, actual, code_fixes, data_fixes, module, name, origin,
                                space, window, oracle) if code_tables else []
    claimed = {c["public"] for c in claims} | {
        p for p, o in publics.items() for t in table_report
        if t["object_offset"] <= o < t["object_offset"] + t["size"]}
    data_public_report = [dict(d, address=(placements[d["segment"]] + d["offset"]) & 0xFFFF,
                               unique=placement_report[d["segment"]]["unique"])
                          for d in sorted(data_publics.values(), key=lambda d: (d["segment"], d["offset"]))]
    # A claim that matches exactly but uses an unproven symbol is a CODE_MATCH: code and every
    # field equation equal under the declared value, the listed bindings not independently proven.
    bound = ((binding or {}).get("symbols") or {})
    unproven_names = {n for n, s in bound.items() if s.get("unproven")}
    unproven_keys = {(n, m["offset"]) for n, s in bound.items() for m in s.get("members", []) if m.get("unproven")}
    for r in reports:
        state = states.get(r["public"])
        used = sorted((state["names"] & unproven_names) |
                      {f"{k[0]}+{k[1]:#x}" for k in (f["key"] for f in state["v4"] + state["far_fields"])
                       if k in unproven_keys}) if state else []
        if r.get("exact") and used:
            r.update(exact=False, state="CODE_MATCH", unproven=used)
    return {"exact": all(r["exact"] for r in reports), "object_sha256": sha(obj_data),
            "placements": placement_report, "data_publics": data_public_report,
            **({"provider_span_aliases": span_aliases} if span_aliases else {}),
            **({"far_placements": far_placements} if far_placements else {}),
            **({"tables": table_report} if table_report else {}),
            "object_order": _object_order(reports, states, code_fixes),
            "space": space.name, "origin": origin, "emitted_size": len(actual),
            "frame": next(iter(frames)) if frames else None,
            "segment": segment, "claims": reports,
            "drafts": sorted(({"public": p, "object_offset": o} for p, o in publics.items() if p not in claimed),
                             key=lambda d: d["object_offset"]),
            "unreferenced_external_declarations": [e for e in module.externals
                                                   if e not in {f["target"].get("name") for f in obligations}],
            "fixup_thread_declarations": [entry for record in module.fixups for entry in record["decoded"]],
            "record_types": [r["type"] for r in module.records], "proof_scope": GROUP_PROOF_SCOPE}


def check_data_group(obj_data, oracle, *, binding, group_id):
    """A data-only C object: a module that defines initialized DGROUP data and no code (e.g. a
    string or table module). Its CODE segment must be empty; every segment with content is a
    placed DGROUP segment judged exactly as in a group (initialized content equal to the original
    bytes, linked near/far pointer and segment-word fields), and every placement must be fixed by
    content that occurs once in DGROUP. Its data publics ground other groups' externs."""
    module = OmfReader().read(obj_data, "candidate")
    require(binding is not None and binding.get("placements") and binding.get("target_id") == group_id,
            "A data-only group needs its own binding with placements")
    placements = binding["placements"]
    segment, name, actual = code_segment(module, placed=tuple(placements))
    require(len(actual) == 0 and not any(p["segment"] == name for p in module.publics),
            "A data-only group emits no code")
    dgroup_members = {module.segment_defs[i - 1]["name"] for g in module.groups if g["name"] == "DGROUP"
                      for i in g["segments"] if 1 <= i <= len(module.segment_defs)}
    data_publics = _data_publics(module, placements, dgroup_members, name)
    obligations = fixes(module)
    require(all(f["segment"] in placements for f in obligations), "Data-only fixups must lie in placed segments")
    require(binding["fixups"] == obligations, "Ordered symbolic fixup obligations changed")
    require(binding["declarations"] == declarations(module), "Bound object declarations changed")
    symbols = binding.get("symbols", {})
    far_symbols = {n: s for n, s in symbols.items() if s.get("kind") in FAR_KINDS}
    require(set(symbols) == set(far_symbols), "Data-only groups bind far symbols only")
    hull = {"space": "root", "segment": 0, "offset": 0, "size": 0, "id": group_id}
    for symbol in far_symbols.values():
        far_ground(symbol, hull, oracle)
    used = {f["target"].get("name") for f in obligations
            if f["loc_type"] in (2, 3) and f["target"].get("kind") == "external"}
    require(set(far_symbols) == used, "Missing or unused grounded far symbol")
    space = oracle.spaces["root"]
    report = _check_placements(module, placements, {}, binding, space, oracle, obligations, far_symbols)
    require(all(r["unique"] for r in report.values()),
            "Every data-only placement must be fixed by initialized content that occurs once in DGROUP")
    return {"exact": True, "object_sha256": sha(obj_data), "space": "root", "placements": report,
            "data_publics": [dict(d, address=(placements[d["segment"]] + d["offset"]) & 0xFFFF, unique=True)
                             for d in sorted(data_publics.values(), key=lambda d: (d["segment"], d["offset"]))]}


def compile_data_group(source_text, profile, flags, workdir, *, binding, group_id):
    """Compile exactly the given C source text and judge it as a data-only group."""
    from pathlib import Path
    from oracle import Oracle
    from compiler import compile_c
    result = compile_c(source_text, profile, flags=flags, workdir=Path(workdir))
    require(result.ok, "Historical compilation failed: " + result.log)
    report = check_data_group(result.obj_bytes, Oracle.load(), binding=binding, group_id=group_id)
    report["includes"] = result.includes
    return result, report


def compile_group(source_text, profile, flags, claims, workdir, *, binding=None, group_id=None, language="c", tables=()):
    """Compile (C) or assemble (MASM) exactly the given source text, the bytes the caller
    hashed, and judge it. ASM claims report ASM_EXACT/CANDIDATE_ASM."""
    from pathlib import Path
    from oracle import Oracle
    require(language in ("c", "asm"), "Unknown source language")
    require(language == "asm" or not tables, "Code tables are claimed from MASM sources only")
    oracle = Oracle.load()
    work = Path(workdir)
    if language == "asm":
        from assembler import assemble_asm
        work.mkdir(parents=True, exist_ok=True)
        staged = work / "GROUP.ASM"
        staged.write_bytes(source_text.encode("ascii"))
        result = assemble_asm(staged, profile, flags=flags, workdir=work / "asm")
    else:
        from compiler import compile_c
        result = compile_c(source_text, profile, flags=flags, workdir=work)
    require(result.ok, "Historical compilation failed: " + result.log)
    report = check_group(result.obj_bytes, claims, oracle, binding=binding, group_id=group_id, code_tables=tables)
    if language == "asm":
        for claim in report["claims"]:
            claim["state"] = {"CODE_EXACT": "ASM_EXACT", "CANDIDATE_C": "CANDIDATE_ASM"}.get(claim["state"],
                                                                                           claim["state"])
    report["language"] = language
    report["includes"] = result.includes if language == "c" else {}
    return result, report
