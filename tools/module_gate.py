# One external declared under two spellings that differ only in case: /Gc folds them to one
# Pascal external, so the compiler sees two objects where the program has one.
EXTERN_DECL = re.compile(r"^[ \t]*extern\b[^;(]*;", re.M)
CASE_ALIAS_DEBT = read_json(ROOT / "evidence/case-alias-debt.json")["aliases"] \
    if (ROOT / "evidence/case-alias-debt.json").exists() else {}


def case_aliases(source_bytes):
    """Sorted upper-case names of externs declared (as data) under more than one spelling."""
    text = re.sub(r"/\*.*?\*/", " ", source_bytes.decode("latin-1"), flags=re.S)
    spellings = {}
    for decl in EXTERN_DECL.findall(text):
        for name in re.findall(r"([A-Za-z_]\w*)\s*(?:\[[^\]]*\]\s*)*(?=[,;])", decl):
            spellings.setdefault(name.upper(), set()).add(name)
    return sorted(k for k, v in spellings.items() if len(v) > 1)


def require_no_case_alias(source_bytes, key, language="c"):
    """Refuse new case-folded extern aliases; listed debt keeps exactly its own."""
    if language != "c":
        return
    extra = sorted(set(case_aliases(source_bytes)) - set(CASE_ALIAS_DEBT.get(key, [])))
    require(not extra, "One external declared under two case spellings (a second C name for one object): "
            + ", ".join(extra))


PLACEMENT_DEBT = set(read_json(ROOT / "evidence/placement-debt.json")["targets"])     if (ROOT / "evidence/placement-debt.json").exists() else set()


def _placed_support(placement_report, states, reports):
    """Fields into a placed segment without unique initialized content are proven only by
    internal consensus: the same (segment, addend) at two or more distinct original instruction
    starts inside CODE_EXACT claims (as _internal_support for v4). Different addends never support
    each other: P + A is one unknown per field once the layout is the source's choice. Runs to a
    fixpoint, since a refused claim withdraws its sites.

    Claims accepted under the earlier rule (content equality alone, or two distinct uninitialized
    addends) are listed in evidence/placement-debt.json; they keep their state but report the
    unsupported fields as `placement_debt`. The list may only shrink: validation refuses stale
    entries, and a claim not listed gets no exemption."""
    weak = {name for name, r in placement_report.items() if not r["unique"]}
    if not weak:
        return
    by_public = {r["public"]: r for r in reports}
    for state in states.values():
        for field in state["placed"]:
            for equation in state["equations"]:
                if equation.get("kind") == "placed data" and equation["offset"] == field["offset"]:
                    equation["support"] = "internal consensus" if field["key"][0] in weak else "unique content"
    changed = True
    while changed:
        changed = False
        exact = [p for p in states if by_public[p].get("exact")]
        sites = {}
        for public in exact:
            for field in states[public]["placed"]:
                if field["key"][0] in weak and field["equal"]:
                    sites.setdefault(field["key"], set()).add(field["insn"])
        for public in exact:
            lacking = sorted({f["key"] for f in states[public]["placed"]
                              if f["key"][0] in weak and len(sites.get(f["key"], ())) < 2})
            if lacking and by_public[public]["target_id"] in PLACEMENT_DEBT:
                by_public[public]["placement_debt"] = [f"{n}+{k}" for n, k in lacking]
            elif lacking:
                by_public[public].update(exact=False, state="REFUSED",
                                         reason="placed field without unique content lacks a second equal "
                                                "claimed site: " + ", ".join(f"{n}+{k}" for n, k in lacking))
                changed = True


_CANDIDATE_FRAMES = {}


def _candidate_frames(oracle):
    """Every paragraph the original stores as a frame: relocation site frames, relocated
    segment words of every space, and RTLink vector destinations. A superset of the code
    frames CS can hold (data frames only add windows, i.e. constraints)."""
    # Keyed by id, holding the oracle itself: a collected test oracle's id can be reused.
    key = id(oracle)
    if key not in _CANDIDATE_FRAMES or _CANDIDATE_FRAMES[key][0] is not oracle:
        frames = set()
        for space in oracle.spaces.values():
            for r in space.relocations:
                if r.get("segment") is not None:
                    frames.add(r["segment"])
                if r.get("image_offset") is not None and r["image_offset"] + 2 <= len(space.data):
                    frames.add(struct.unpack_from("<H", space.data, r["image_offset"])[0])
        if getattr(oracle, "mz", None) is not None:  # RTLink vectors need the MZ image
            frames.update(v["target_segment"] for v in _code_vectors(oracle).values())
        _CANDIDATE_FRAMES[key] = (oracle, frames)
    return _CANDIDATE_FRAMES[key][1]


def _frame_invariant(state, space, oracle):
    """True when every equal near call of the claim reaches its callee under every candidate
    frame whose 64K window holds the whole claim, and at least one such frame exists."""
    near = state["near"]
    if not near or not all(n["equal"] for n in near):
        return False
    lo, hi = state["position"], state["position"] + len(state["piece"])
    windows = [base for base in ((f - space.link_segment) * 16 for f in _candidate_frames(oracle))
               if base <= lo and hi <= base + 0x10000]
    return bool(windows) and all(base <= n["pair_start"] and n["field_end"] <= base + 0x10000 and
                                 base <= n["callee_at"] < base + 0x10000 for base in windows for n in near)


def _solved_frame(states, cs_proven, table_words, space, oracle, origin, publics):
    """Root code entered only through CS-relative words. Each own-segment offset16 word is the
    linker equation V = origin + A - base (mod 64K) on original bytes, so the words fix the frame:
    - words inside claims not yet CS-proven (all must hold);
    - `table_words`: own-segment words in unclaimed regions of the object (descriptor and dispatch
      tables), each at an original position without an MZ relocation (all must hold).
    Returns (base, solved_claims, entered_claims, word_count) for the single candidate frame (a
    paragraph the original stores) whose 64K window holds every such claim, word and target and
    satisfies every equation, else None. Entered claims are those whose entry a table word names."""
    if space.name != "root":
        return None
    claims = {p: s for p, s in states.items() if p not in cs_proven and s["own"]}
    by_offset = {o: p for p, o in publics.items()}
    entered = {by_offset[a] for a, _, _ in table_words if by_offset.get(a) in states}
    count = sum(len(s["own"]) for s in claims.values()) + len(table_words)
    if count < 2 or not (claims or entered):
        return None
    spans = [(s["position"], s["position"] + len(s["piece"])) for s in claims.values()]
    spans += [(min(origin + at, origin + a), max(origin + at + 2, origin + a + 1)) for a, at, _ in table_words]
    fits = []
    for base in sorted((f - space.link_segment) * 16 for f in _candidate_frames(oracle)):
        if not all(base <= lo and hi <= base + 0x10000 for lo, hi in spans):
            continue
        if all((origin - base + own["addend"]) & 0xFFFF ==
               struct.unpack_from("<H", s["expected"], own["offset"])[0]
               for s in claims.values() for own in s["own"]) and \
                all((origin - base + a) & 0xFFFF == v for a, _, v in table_words):
            fits.append(base)
    if len(fits) != 1:
        return None
    return fits[0], set(claims), entered - cs_proven, count


def _code_vectors(oracle):
    """The original RTLink vector records (tu_census decoding, checked against the manager)."""
    from tu_census import overlay_vectors
    overlays = {n: s for n, s in oracle.spaces.items() if s.descriptor and s.descriptor["flags"] == 4}
    return overlay_vectors(oracle, overlays)


def _bracket_frame(space, position):
    """The site frame bracketing `position` in a monotone overlay relocation table, else None."""
    rows = sorted(space.relocations, key=lambda r: r["image_offset"])
    if any(a["segment"] > b["segment"] for a, b in zip(rows, rows[1:])):
        return None
    before = [r for r in rows if r["image_offset"] <= position]
    after = [r for r in rows if r["image_offset"] >= position]
    if before and after and before[-1]["segment"] == after[0]["segment"]:
        return before[-1]["segment"]
    return None


def _other_overlay_frame(oracle, space, segment, offset):
    """A relocated far word segment:offset that lands inside an overlay claim with a frame other
    than the claim's names another overlay's segment when another code overlay holds that link
    address and its own relocation sites bracket that position with exactly `segment`. A far
    word stores its target segment's frame (probe), and the claim's own sites name a different
    frame there, so the linker resolved the reference into the other overlay's segment."""
    for other in oracle.spaces.values():
        if other.name == space.name or not (other.descriptor and other.descriptor["flags"] == 4):
            continue
        position = (segment - other.link_segment) * 16 + offset
        if not 0 <= position < other.size:
            continue
        if _bracket_frame(other, position) == segment:
            return True
        # At the start of a segment before its first relocation: the next record names the
        # word's frame and every earlier record a smaller one (monotone table), so the only
        # segment of that frame there is the one beginning at or before the next record.
        rows = sorted(other.relocations, key=lambda r: r["image_offset"])
        if any(a["segment"] > b["segment"] for a, b in zip(rows, rows[1:])):
            continue
        after = [r for r in rows if r["image_offset"] >= position]
        before = [r for r in rows if r["image_offset"] < position]
        if after and after[0]["segment"] == segment and (not before or before[-1]["segment"] < segment)                 and position >= (segment - other.link_segment) * 16:
            return True
    return False


def _foreign_frame(space, frame, segment):
    """True when a far word of frame `segment` cannot enter the code segment of floor `frame`
    in overlay `space`, so it names a segment of another overlay sharing the area.

    A relocated segment word stores its target segment's floor, or its group's frame, which
    is the floor of the group's lowest member and never above any member's floor (linker
    rule). The claim's segment has floor `frame` (bracketed), so:
    - `segment` > `frame`: neither a segment of floor `segment` nor a group of that frame
      can hold the claim's segment;
    - `segment` >= the link segment and a record of this overlay with a smaller site frame
      lies at or beyond the end of paragraph `segment` (record field included): the segment
      holding that record starts before the paragraph and covers all of it, so no segment
      of this overlay starts there and none has floor `segment` (nor any group frame).
    A frame below the link segment is never excused (a group reaching across sections is
    not refuted by this overlay's records)."""
    if segment > frame:
        return True
    if segment < space.link_segment:
        return False
    paragraph_end = (segment - space.link_segment) * 16 + 16
    return any(r["segment"] < segment and r["image_offset"] + 2 >= paragraph_end for r in space.relocations)


def _site_frame(target, space, oracle, hull, grouped=False):
    """("evidence"|"refused", row): the CS frame named by the overlay's own relocation sites.

    RTLink 6.10 writes each overlay relocation record as (site offset, site segment), the
    site segment being the frame of the code segment holding the site: the paragraph floor
    of that segment's start, the same frame every relocated far reference into the segment
    stores (probe: evidence/rtlink-probe/site-frames/). Frames therefore never decrease with
    position. If the last record before the claim's end and the first record from its start
    on name one frame F, the segments holding them both have frame F, so every segment
    between them does, and the claim (one original function, one segment) runs with CS F.
    A relocation-free segment between two frames is never covered (the brackets differ).
    Section start: an overlay's first segment begins at payload position 0, so no floor is
    below the link segment. A claim with no record before its end therefore has the link
    segment as lower bracket, which proves F only when the first record from the claim's
    start on names the link segment itself.
    Only for a code segment outside every group: a grouped segment's records still name its
    floor while far references use the group frame (probe $$OVLVEC), so a candidate object
    grouping its CODE segment is refused.
    Refused unless the records are monotone, every relocated far word (stored segment plus
    the offset word before it, any space; a decoded vector naming another overlay excepted)
    that lands inside the object uses F, and F's 64K window holds the whole object.
    A word of another frame G is excused only when it cannot enter the claim's segment
    (`_foreign_frame`): G > F, or G cannot be the floor of any segment of this overlay."""
    if not (space.descriptor and space.descriptor["flags"] == 4):
        return None
    row = {"kind": "overlay site frame", "space": space.name}
    if grouped:
        # Probe: a grouped segment's records name its own floor; calls use the group frame.
        return "refused", dict(row, reason="code segment is a group member; site frame is not its CS")
    rows = sorted(space.relocations, key=lambda r: r["image_offset"])
    start = space.position(target["segment"], target["offset"])
    end = start + target["size"]
    if any(a["segment"] > b["segment"] for a, b in zip(rows, rows[1:])):
        return "refused", dict(row, reason="overlay relocation site frames are not monotone")
    before = [r for r in rows if r["image_offset"] < end]
    after = [r for r in rows if r["image_offset"] >= start]
    # Section start: the segment holding position 0 has floor exactly the link segment.
    lower = (before[-1]["segment"], before[-1]["index"]) if before else (space.link_segment, "section-start")
    if not after or lower[0] != after[0]["segment"]:
        return "refused", dict(row, reason="no relocation records of one site frame bracket the claim")
    frame = lower[0]
    row.update(frame=frame, bracket_relocation_indices=[lower[1], after[0]["index"]])
    lo, hi = hull
    base = (frame - space.link_segment) * 16
    if not (base <= lo and hi <= base + 0x10000):
        return "refused", dict(row, reason="site frame window does not hold the whole object")
    # A decoded RTLink vector's jump word enters only the overlay its descriptor index names.
    elsewhere = {v["position"] + 6 for v in _code_vectors(oracle).values() if v["target_space"] != space.name}
    for source in oracle.spaces.values():
        for record in source.relocations:
            at = record["image_offset"]
            if at < 2 or (source.name == "root" and at in elsewhere):
                continue
            segment = record["stored_word"]
            base_f = (segment - space.link_segment) * 16
            if segment == frame or base_f >= hi or base_f + 0x10000 <= lo:
                continue  # same frame, or no offset under this segment can reach the object
            # `mov r16, SEG X` (B8+r imm16): the bytes before the word are an opcode, not an offset,
            # so its offset is unknown; every other relocated word (CALL/JMP FAR operand, `dd`
            # pointer) stores its offset in the word before it.
            # A relocated segment value is the frame of its target's segment (probe), so a segment
            # load of another frame refers to another segment; only a group frame could alias ours,
            # and MSC medium-model code segments are never grouped (a grouping candidate is refused).
            if at >= 1 and 0xb8 <= source.data[at - 1] <= 0xbf:
                continue
            linked = base_f + struct.unpack_from("<H", source.data, at - 2)[0]
            if not lo <= linked < hi:
                continue
            offset = struct.unpack_from("<H", source.data, at - 2)[0]
            if _other_overlay_frame(oracle, space, segment, offset):
                continue  # the linker resolved it into another overlay's segment of frame `segment`
            if _foreign_frame(space, frame, segment):
                continue  # frame `segment` names no segment (or group) that can hold the claim
            return "refused", dict(row, reason=f"relocated far word {source.name}+{at - 2:#x} "
                                               f"enters the object with frame {segment:04x}")
    return "evidence", row


def _reached_near_frames(target, space, oracle, hull):
    """Root claims with no relocated far caller: an original near CALL (`E8`, optionally after
    PUSH CS) outside the object whose rel16 lands on the claim entry, reached by recursive
    descent from an entry that an original relocated CALL FAR names with exactly segment F and
    that offset, runs with CS = F (descent and near calls never change CS), so the claim is
    entered with CS = F. The landing is computed in F's window, so wrap is accounted for."""
    from binding import reachable_from_entry
    entry = space.position(target["segment"], target["offset"])
    lo, hi = hull
    data = space.data
    far_entries = set()
    # Relocated CALL FARs in any space name an entry with CS = their stored segment; a root
    # entry is always resident, so overlay callers witness it as well as root callers do.
    for holder in oracle.spaces.values() if space.name == "root" else [space]:
        for r in holder.relocations:
            at = r["image_offset"] - 3
            if at >= 0 and holder.data[at] == 0x9a:
                off, seg = struct.unpack_from("<HH", holder.data, at + 1)
                if 0 <= (seg - space.link_segment) * 16 + off < space.size:
                    far_entries.add((seg, off))
    found = []
    for seg, off in sorted(far_entries):
        base = (seg - space.link_segment) * 16
        if not (base <= entry < base + 0x10000):
            continue
        try:
            reached = reachable_from_entry(oracle, f"{space.name}:{seg:04x}:{off:04x}")
        except ValueError:
            continue
        for at in reached:
            if data[at] not in (0xe8, 0xe9) or (at < hi and lo < at + 3):  # near CALL or JMP keep CS
                continue
            rel = struct.unpack_from("<H", data, at + 1)[0]
            if base + ((at - base + 3 + rel) & 0xFFFF) == entry:
                found.append({"frame": seg, "kind": "reached near CALL", "space": space.name,
                              "image_offset": at, "entry": f"{space.name}:{seg:04x}:{off:04x}"})
        if found:
            break
    return found[:1]


def _link_holders(oracle, space, segment, offset):
    """Spaces other than `space` whose memory extent (descriptor paragraphs, not just the
    file payload) holds the link address segment:offset."""
    return sorted(n for n, s in oracle.spaces.items() if n != space.name and
                  0 <= (segment - s.link_segment) * 16 + offset <
                  max(s.size, 16 * (s.descriptor or {}).get("f8", 0)))


def _frame_evidence(target, space, oracle, hull, grouped=False):
    """(evidence, unusable): independent original far entries naming this claim's CS.

    Root: the segment words of the reviewed, relocated CALL FARs that enter the target
    (unchanged). An overlay claim's code runs only while its overlay is loaded at its
    link address, so a far entry names its CS only if it provably reaches this overlay:
    - an RTLink vector record whose decoded destination (descriptor index -> this
      overlay, segment:offset -> the claim entry) is the claim; the manager loads the
      section and far-jumps with that segment;
    - a reviewed relocated CALL FAR inside the same overlay, relocated by that overlay's
      own table and outside the whole object: its caller is resident, so its own section
      is, and the destination lies in it;
    - a reviewed relocated CALL FAR from another space, only when no other space holds
      that link address (otherwise it may enter another overlay sharing the segment);
    - a reviewed relocated far pointer (any space) naming the entry, under the same
      unshared-link-address condition;
    - the overlay's own relocation site frames bracketing the claim (`_site_frame`).
    `hull` is the object's (start, end) in the claim's space; `grouped` says the candidate
    object puts its CODE segment in a group."""
    evidence, unusable = [], []
    calls = [c for c in target.get("call_sites", []) if c["kind"] == "far_call"]
    if space.name == "root":
        for call in calls:
            caller = oracle.spaces[call["space"]]
            evidence.append({"frame": struct.unpack_from("<H", caller.data, call["image_offset"] + 3)[0],
                             "kind": "relocated CALL FAR", "space": caller.name,
                             "image_offset": call["image_offset"]})
        # A relocated far pointer naming the entry (callback/vector table) is a far transfer
        # target with CS = its stored segment, like a relocated CALL FAR. Overlay entries take
        # it only for an unshared link address (below).
        for ptr in (c for c in target.get("call_sites", []) if c["kind"] == "far_pointer"):
            holder = oracle.spaces[ptr["space"]]
            evidence.append({"frame": struct.unpack_from("<H", holder.data, ptr["image_offset"] + 2)[0],
                             "kind": "relocated far pointer", "space": holder.name,
                             "image_offset": ptr["image_offset"]})
        if not evidence:
            evidence += _reached_near_frames(target, space, oracle, hull)
        return evidence, unusable
    entry = space.position(target["segment"], target["offset"])
    for vector in _code_vectors(oracle).values():
        if vector["target_space"] == space.name and vector["target_position"] == entry:
            evidence.append({"frame": vector["target_segment"], "kind": "rtlink-vector",
                             "vector": f"root:{vector['segment']:04x}:{vector['offset']:04x}",
                             "descriptor_index": vector["descriptor_index"]})
    lo, hi = hull
    for call in calls:
        caller = oracle.spaces[call["space"]]
        at = call["image_offset"]
        offset, segment = struct.unpack_from("<HH", caller.data, at + 1)
        row = {"frame": segment, "space": caller.name, "image_offset": at}
        if caller.name == space.name:
            if at < hi and lo < at + 5:
                unusable.append(dict(row, reason="same-overlay CALL FAR inside the object"))
                continue
            evidence.append(dict(row, kind="same-overlay CALL FAR",
                                 relocation_index=next(r["index"] for r in caller.relocations
                                                       if r["image_offset"] == at + 3)))
            continue
        holders = _link_holders(oracle, space, segment, offset)
        if holders:
            unusable.append(dict(row, reason="link address also held by " + ", ".join(holders)))
            continue
        evidence.append(dict(row, kind="cross-space CALL FAR"))
    # A reviewed relocated far pointer naming the entry (match.get_target checks it) is a far
    # transfer target with CS = its stored segment, but only when no other space holds that
    # link address: otherwise it may name another overlay's code sharing the address.
    for ptr in (c for c in target.get("call_sites", []) if c["kind"] == "far_pointer"):
        holder = oracle.spaces[ptr["space"]]
        offset, segment = struct.unpack_from("<HH", holder.data, ptr["image_offset"])
        row = {"frame": segment, "space": holder.name, "image_offset": ptr["image_offset"]}
        holders = _link_holders(oracle, space, segment, offset)
        if holders:
            unusable.append(dict(row, reason="far pointer link address also held by " + ", ".join(holders)))
            continue
        evidence.append(dict(row, kind="relocated far pointer (unshared link address)"))
    site = _site_frame(target, space, oracle, hull, grouped)
    if site:
        (evidence if site[0] == "evidence" else unusable).append(site[1])
    return evidence, unusable


def _check_unplaced(module, placements, symbols):
    """A v4 external address may not fall inside this object's own placed DGROUP segment.
    Definitions never overlap: a provider public's whole placed segment may not overlap this
    object's placed segments, and two provider spans may not overlap. Returns the v4 addresses
    that lie inside a provider span (aliases, recorded as debt: v4 symbols are addresses
    without extent, not definitions; the linked-value aliasing rule is _check_provider_aliases)."""
    lengths = {d["name"]: d["length"] for d in module.segment_defs}
    spans = [(n, s["offset"], s["offset"] + s["span"]) for n, s in symbols.items() if s.get("kind") == PUBLIC_KIND]
    inside = []
    for name, symbol in symbols.items():
        if symbol.get("kind") == PUBLIC_KIND:
            lo, hi = symbol["range"]
            for seg, at in placements.items():
                require(not (at < hi and lo < at + lengths.get(seg, 0)),
                        f"Provider segment of {name} overlaps placed segment {seg} of this object")
            require(not any(other != name and a < symbol["offset"] + symbol["span"] and symbol["offset"] < b
                            for other, a, b in spans), f"Provider public span of {name} overlaps another symbol")
            continue
        values = [symbol["offset"]] + [(symbol["offset"] + m["offset"]) & 0xFFFF for m in symbol.get("members", [])]
        for seg, at in placements.items():
            require(not any(at <= v < at + lengths.get(seg, 0) for v in values),
                    f"v4 address of {name} lies inside placed segment {seg}")
        inside += [f"{name}@{v:#06x} in {other}" for v in values for other, a, b in spans if a <= v < b]
    return inside


def _check_provider_aliases(symbols, states):
    """The v4 aliasing rule for provider fields: every linked value S + A that a provider
    public field writes must differ from every other symbol's linked value T + j."""
    others = {}
    for name, symbol in symbols.items():
        if symbol.get("kind") != PUBLIC_KIND:
            for v in [symbol["offset"]] + [(symbol["offset"] + m["offset"]) & 0xFFFF
                                           for m in symbol.get("members", [])]:
                others.setdefault(v, name)
    for state in states.values():
        for field in state["v4"]:
            symbol = symbols[field["key"][0]]
            if symbol.get("kind") == PUBLIC_KIND:
                value = (symbol["offset"] + field["key"][1]) & 0xFFFF
                require(value not in others, f"Provider field {field['key'][0]}+{field['key'][1]} aliases "
                        f"v4 symbol {others.get(value)}")


