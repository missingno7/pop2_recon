def _rel16_site(rows, at):
    """The decoded instruction whose rel16 operand is the field at `at`.

    Returns (kind, instruction offset, preceded by a decoded PUSH CS): kind is "call" for
    E8, "jmp" for E9 and "jcc" for 0F 80..8F. Matching bytes alone never qualify."""
    by_address = {insn.address: bytes(insn.bytes) for insn in rows}
    near = by_address.get(at - 1, b"")
    if len(near) == 3 and near[0] in (0xe8, 0xe9):
        return ("call" if near[0] == 0xe8 else "jmp"), at - 1, near[0] == 0xe8 and by_address.get(at - 2) == b"\x0e"
    jcc = by_address.get(at - 2, b"")
    if len(jcc) == 4 and jcc[0] == 0x0f and 0x80 <= jcc[1] <= 0x8f:
        return "jcc", at - 2, False
    raise ValueError("Self-relative field is not the rel16 operand of a decoded E8/E9/0F 8x instruction")


def _self_relative(fix, code_name, publics, near_symbols, piece, at, rows, start, end):
    """Classify one LOC1 self-relative rel16 field of a claim (claim-relative `at`).

    Returns (kind, destination, instruction) where kind is "internal" (own CODE segment,
    destination the object offset of an instruction of this claim), "public" (the name of
    a public of this object, called by E8 with or without PUSH CS) or "external" (the name
    of a grounded near-code-entry symbol, called by E8). The destination of an
    own-segment target is the target displacement plus the encoded LEDATA addend, as the
    linker adds the location's contents to `target - (field + 2)`."""
    target, frame = fix["target"], fix["frame"]
    # The value of a self-relative field is a difference of two positions in one frame, so
    # the target-derived frame (MSC F5) and the own CODE segment frame (MASM F0, or F4 the
    # location) give the same 16-bit value. Any other frame is refused.
    require(fix["loc_type"] == 1 and fix["field_width"] == 2 and
            (frame == {"kind": "target_frame", "target": target} or
             (frame.get("kind") == "segment" and frame.get("name") == code_name)),
            "Unsupported self-relative fixup shape")
    kind, insn_at, push_cs = _rel16_site(rows, at)
    addend = struct.unpack_from("<H", piece, at)[0]
    if target.get("kind") == "segment" and target.get("name") == code_name and target.get("method") in (0, 4):
        destination = ((fix["displacement"] or 0) + addend) & 0xFFFF
        if start <= destination < end:
            require(destination - start in {i.address for i in rows},
                    "Self-relative branch target is not an instruction of the claim")
            return "internal", destination, (kind, insn_at, push_cs)
        callee = [name for name, offset in publics.items() if offset == destination]
        require(kind == "call" and callee, "Self-relative own-segment branch leaves its claim")
        return "public", callee[0], (kind, insn_at, push_cs)
    require(target.get("kind") == "external" and target.get("method") == 6 and fix["displacement"] is None,
            "Unsupported self-relative fixup shape")
    require(addend == 0, "Only zero encoded near-call addends are proven")
    # A near CALL, or a tail JMP (E9) to a grounded external near entry: both keep CS.
    require(kind == "call" or (kind == "jmp" and target["name"] in near_symbols and target["name"] not in publics),
            "Only near CALLs (or a tail JMP to an external near entry) may name a near entry")
    if target["name"] in publics:
        return "public", target["name"], (kind, insn_at, push_cs)
    require(target["name"] in near_symbols,
            "Near call target is neither a public of this object nor a grounded near-code entry")
    return "external", target["name"], (kind, insn_at, push_cs)


def _contained(rows, length, proven=()):
    """Control stays inside the claim: direct in-range jumps only, ending in a return or JMP.
    `proven` jumps carry a self-relative fixup whose linked target was proven in the claim."""
    from disasm import _capstone
    cs, xc = _capstone()
    last = None
    for insn in rows:
        if set(insn.groups).intersection((cs.CS_GRP_JUMP,)) and insn.address not in proven:
            require(len(insn.operands) == 1 and insn.operands[0].type == xc.X86_OP_IMM and
                    0 <= insn.operands[0].imm < length,
                    "Jump leaves the claim or is indirect")
        if bytes(insn.bytes) != b"\x90":
            last = insn
    require(last is not None and (set(last.groups).intersection((cs.CS_GRP_RET, cs.CS_GRP_IRET)) or
                                  last.mnemonic == "jmp"),
            "Control can fall through out of the claim")


def _own_segment(fix, code_name):
    """An offset16 field addressing this object's own CODE segment (switch tables, CS: operands)."""
    target, frame = fix["target"], fix["frame"]
    own = {"kind": "segment", "name": code_name}
    return (not fix["self_relative"] and fix["loc_type"] == 1 and fix["field_width"] == 2 and
            {k: target.get(k) for k in ("kind", "name")} == own and
            (frame.get("kind") == "target_frame" or {k: frame.get(k) for k in ("kind", "name")} == own))


def _tables(addends, start):
    """Jump tables: a run of consecutive own-segment words that another own-segment field
    (the `jmp cs:[bx+T]` displacement) points at. `addends` maps each field's claim-relative offset
    to its object offset T (LEDATA word + FIXUPP displacement: MASM may use either), so T - start
    locates the table inside the claim."""
    present = set(addends)
    starts = sorted({target - start for target in addends.values()} & present)
    runs = []
    for first in starts:
        last = first
        while last + 2 in present:
            last += 2
        runs.append((first, last + 2))
    merged = []
    for lo, hi in sorted(runs):
        if merged and lo < merged[-1][1]:
            merged[-1] = (merged[-1][0], max(hi, merged[-1][1]))
        else:
            merged.append((lo, hi))
    return merged


def _inline_data(piece, own_targets, tables, start):
    """[(lo, hi)] of one-byte or one-word CS: variables a claim keeps between its code (`busy DB 0` after a RETF, with a
    later branch target behind it): the variable starts where decoding from the claim start reaches the end of a
    return or JMP, a CS:-prefixed operand of the claim addresses it with that width, and the byte after it is the
    target of a direct branch decoded before it. The bytes are compared as ordinary bytes like any other."""
    cs, xc = _capstone()
    engine = cs.Cs(cs.CS_ARCH_X86, cs.CS_MODE_16)
    engine.detail = True
    found = []
    for t in sorted({value - start for at, value in own_targets.items() if not any(lo <= at < hi for lo, hi in tables)}):
        if not 0 < t < len(piece) or any(lo <= t < hi for lo, hi in tables):
            continue
        rows, cursor, whole = [], 0, True
        for lo, hi in sorted([*tables, *found]) + [(t, t)]:
            if lo > t:
                break
            part = list(engine.disasm(piece[cursor:lo], cursor))
            whole = whole and sum(i.size for i in part) == lo - cursor
            rows, cursor = rows + part, hi
        if not whole or not rows or not (set(rows[-1].groups).intersection((cs.CS_GRP_RET, cs.CS_GRP_IRET)) or
                                         rows[-1].mnemonic == "jmp"):
            continue
        widths = {o.size for i in rows for o in i.operands
                  if o.type == xc.X86_OP_MEM and o.mem.segment == xc.X86_REG_CS and o.mem.base == o.mem.index == 0 and
                  i.disp_size == 2 and own_targets.get(i.address + i.disp_offset) == t + start}
        branches = {i.operands[0].imm & 0xFFFF for i in rows
                    if cs.CS_GRP_JUMP in i.groups and i.operands and i.operands[0].type == xc.X86_OP_IMM}
        if len(widths) == 1 and (width := widths.pop()) in (1, 2) and t + width in branches:
            found.append((t, t + width))
    return found


def _decode(piece, tables):
    """Decode every byte outside the jump tables, each code run from its own start."""
    cs, _ = _capstone()
    engine = cs.Cs(cs.CS_ARCH_X86, cs.CS_MODE_16)
    engine.detail = True
    rows, cursor = [], 0
    for lo, hi in list(tables) + [(len(piece), len(piece))]:
        chunk = piece[cursor:lo]
        part = list(engine.disasm(chunk, cursor))
        require(sum(i.size for i in part) == len(chunk), "Claim code does not decode completely")
        rows += part
        cursor = hi
    return rows


def _dgroup_home(binding, space, oracle):
    """(space holding initialized DGROUP, image offset of the DGROUP paragraph)."""
    if "dgroup_segment" in binding:
        from far_binding import _ground_segment
        seg_spec = binding["dgroup_segment"]
        # The paragraph witnesses are startup words in root; no candidate extent to avoid there.
        _ground_segment({"segment": seg_spec["segment"], "witnesses": seg_spec["witnesses"]},
                        {"space": "root", "segment": 0, "offset": 0, "size": 0}, oracle)
        homes = [sp for sp in oracle.spaces.values()
                 if 0 <= (seg_spec["segment"] - sp.link_segment) * 16 < sp.size]
        require(len(homes) == 1, "DGROUP paragraph does not lie in exactly one space")
        home = homes[0]
        return home, (seg_spec["segment"] - home.link_segment) * 16
    return space, (binding["frame"]["segment"] - space.link_segment) * 16


def _far_placements(module, spec, obligations, oracle):
    """The object's own FAR_DATA segments (docs/far-call-binding.md "Own far data"): {name: paragraph}, as a report.

    A paragraph-aligned FAR_DATA segment outside every group, completely initialized and without fixups, whose bytes
    occur exactly once in the whole original image, at a paragraph boundary and without a relocated word. The linker
    starts such a contribution on a paragraph and frames its fields by it, so that content fixes the paragraph."""
    report = {}
    grouped = {i for g in module.groups for i in g["segments"]}
    for index, seg in enumerate(module.segment_defs, 1):
        if seg["name"] not in spec:
            continue
        paragraph, content = spec[seg["name"]], module.segments.get(seg["name"])
        require(seg["class"] == "FAR_DATA" and seg["alignment"] == 3 and index not in grouped and
                sum(s["name"] == seg["name"] for s in module.segment_defs) == 1,
                "Own far data must be one paragraph-aligned FAR_DATA segment outside every group")
        require(not any(p["segment"] == seg["name"] for p in module.publics) and
                not any(f["segment"] == seg["name"] for f in obligations),
                "Own far data with publics or fixups is not proven")
        require(content is not None and len(content) == seg["length"] >= 16 and
                _tiled(seg["length"], module.initialized_ranges.get(seg["name"], [])),
                "Own far data must be completely initialized")
        homes = [sp for sp in oracle.spaces.values() if type(paragraph) is int and
                 0 <= (paragraph - sp.link_segment) * 16 <= sp.size - seg["length"] and
                 sp.data[(paragraph - sp.link_segment) * 16:][:seg["length"]] == content]
        require(len(homes) == 1 and sum(_count(sp.data, content) for sp in oracle.spaces.values()) == 1,
                "Own far data is not the original content of that paragraph, or occurs elsewhere too")
        start = (paragraph - homes[0].link_segment) * 16
        require(not any(start - 1 <= r["image_offset"] < start + seg["length"] for r in homes[0].relocations),
                "Own far data overlaps original relocated words")
        report[seg["name"]] = {"paragraph": paragraph, "length": seg["length"], "space": homes[0].name}
    require(set(report) == set(spec), "Far placement for a segment the object does not declare")
    return report


def _tiled(length, ranges):
    """True when `ranges` cover [0, length) without hole or overlap."""
    at = 0
    for lo, hi in sorted(ranges):
        if lo != at:
            return False
        at = hi
    return at == length


def _count(data, content):
    hits, at = 0, data.find(content)
    while at >= 0:
        hits, at = hits + 1, data.find(content, at + 1)
    return hits


def _occurs_once(home, dgroup, content):
    hits, at = 0, home.data.find(content, dgroup)
    while at >= 0 and hits < 2:
        hits, at = hits + 1, home.data.find(content, at + 1)
    return hits == 1


def _initialized_with_alignment_holes(ranges, length):
    """Initialized from 0 to the end, except single-byte holes: MSC skips one byte to word-align
    the next item and emits no LEDATA for it; the linker writes zero there. The holes stay in the
    compared content as zero bytes, so every byte of the segment is still compared."""
    merged = []
    for lo, hi in sorted(ranges):
        if merged and lo <= merged[-1][1]:
            merged[-1] = (merged[-1][0], max(merged[-1][1], hi))
        else:
            merged.append((lo, hi))
    return (bool(merged) and merged[0][0] == 0 and merged[-1][1] == length and
            all(b[0] - a[1] == 1 for a, b in zip(merged, merged[1:])))


def _linked_data(seg, content, fields, placements, far_symbols=None, data_symbols=None, code=None):
    """The bytes the linker writes for a placed initialized segment, and the segment-word offsets
    that must carry original MZ relocations. Accepted field forms:
    - a near pointer into this object's placed DGROUP data (offset16, frame DGROUP, target a
      placed segment): P(target) + stored offset + D, mod 64K;
    - a near pointer to another file's DGROUP data (offset16, frame DGROUP, target an external the
      binding grounds independently: a witnessed v4 symbol or a provider data public, never an
      unproven one): its grounded offset + stored offset + D (2026-11-23; DRAW's level tables);
    - a far code pointer (16:16, frame = its target) to an external far code symbol the binding
      grounds independently (accepted exact entry or outside witnesses): that symbol's
      offset and segment, with a zero encoded addend; its segment word is relocated in MZ.
    - a far code pointer into this object's own CODE segment, when the claims' CS frame is witnessed:
      `code` is (segment name, its offset in that frame, its length, the frame, CODE publics); the linker writes
      offset + stored offset + D and the frame, relocated in MZ (2026-11-23)."""
    linked, relocated = bytearray(content), []
    for f in fields:
        target, frame = f["target"], f["frame"]
        if f["loc_type"] == 2:
            # MSC far data: `mov es, [seg word]` reads a CONST word holding the far segment of an
            # external far array (LOC2 base16, frame = its target, zero encoded addend).
            symbol = (far_symbols or {}).get(target.get("name"))
            same_external = {k: frame.get(k) for k in ("kind", "index", "name")} ==                 {"kind": "external", "index": target.get("index"), "name": target.get("name")}
            at = f["segment_offset"]
            require(symbol is not None and symbol.get("kind") in ("segment-base", "far-data") and
                    not f["self_relative"] and f["field_width"] == 2 and target.get("kind") == "external" and
                    f["displacement"] is None and content[at:at + 2] == bytes(2) and
                    (frame == {"kind": "target_frame", "target": target} or same_external),
                    f"Placed segment {seg} segment word at +{at:#x} is not a zero-addend base of a "
                    "grounded far segment symbol")
            linked[at:at + 2] = symbol["segment"].to_bytes(2, "little")
            relocated.append(at)
            continue
        own = (code or ((),) * 5)[4] if code else {}
        if f["loc_type"] == 3 and (target.get("kind") == "segment" or
                                   target.get("kind") == "external" and target.get("name") in own):
            # The target is this object's CODE segment, or an EXTDEF of one of its own CODE publics.
            at, start = f["segment_offset"], own.get(target.get("name"), 0) if target["kind"] == "external" else 0
            same = {k: frame.get(k) for k in ("kind", "name")} == {k: target.get(k) for k in ("kind", "name")}
            require(code is not None and (target["kind"] == "external" or target.get("name") == code[0]) and
                    not f["self_relative"] and f["field_width"] == 4 and content[at + 2:at + 4] == bytes(2) and
                    (frame == {"kind": "target_frame", "target": target} or same),
                    f"Placed segment {seg} far pointer at +{at:#x} is not a pointer into this object's own CODE "
                    "with a witnessed frame")
            entry = start + int.from_bytes(content[at:at + 2], "little") + (f["displacement"] or 0)
            require(0 <= entry < code[2], f"Placed segment {seg} far pointer at +{at:#x} leaves the object's CODE")
            linked[at:at + 4] = ((code[1] + entry) & 0xFFFF).to_bytes(2, "little") + code[3].to_bytes(2, "little")
            relocated.append(at + 2)
            continue
        if f["loc_type"] == 3:
            symbol = (far_symbols or {}).get(target.get("name"))
            same_external = {k: frame.get(k) for k in ("kind", "index", "name")} == \
                {"kind": "external", "index": target.get("index"), "name": target.get("name")}
            at = f["segment_offset"]
            require(symbol is not None and symbol.get("kind") not in ("segment-base", "far-data") and
                    not f["self_relative"] and f["field_width"] == 4 and target.get("kind") == "external" and
                    f["displacement"] is None and content[at:at + 4] == bytes(4) and
                    (frame == {"kind": "target_frame", "target": target} or same_external),
                    f"Placed segment {seg} far pointer at +{at:#x} is not a zero-addend pointer to a "
                    "grounded far code symbol")
            linked[at:at + 4] = symbol["offset"].to_bytes(2, "little") + symbol["segment"].to_bytes(2, "little")
            relocated.append(at + 2)
            continue
        external = (data_symbols or {}).get(target.get("name")) if target.get("kind") == "external" else None
        # An external may also be framed by its own target (F5, as in the code-side v4 equation): its
        # PUBDEF is framed by DGROUP, so the linked value is the same DGROUP offset.
        framed = ({k: frame.get(k) for k in ("kind", "name")} == {"kind": "group", "name": "DGROUP"} or
                  external is not None and frame == {"kind": "target_frame", "target": target})
        require(not f["self_relative"] and f["loc_type"] in (1, 5) and f["field_width"] == 2 and framed and
                ((target.get("kind") == "segment" and target.get("name") in placements) or
                 (external is not None and type(external.get("offset")) is int and not external.get("unproven"))),
                f"Placed segment {seg} fixup at +{f['segment_offset']:#x} is not a DGROUP near pointer "
                "to placed data of this object or to an independently grounded DGROUP symbol")
        at = f["segment_offset"]
        base = external["offset"] if external is not None else placements[target["name"]]
        value = base + int.from_bytes(content[at:at + 2], "little") + (f["displacement"] or 0)
        linked[at:at + 2] = (value & 0xFFFF).to_bytes(2, "little")
    return bytes(linked), relocated


# CONST begins where the C termination table [26c2, 26c6) ends: root+0x20153 `mov di,26c6` (tests re-read it).
CONST_START = 0x26C6


def _selector_references(oracle, home, offset):
    """(space, image offset) of every byte sequence, reached or not, that reads or loads the DGROUP word at
    `offset` directly (mov/push/cmp/les/lds/mov-sreg with a disp16 operand, mov ax/al moffs)."""
    found, word = [], struct.pack("<H", offset)
    for holder in oracle.spaces.values():
        if holder is home:
            continue
        at = holder.data.find(word)
        while at >= 0:
            if at >= 2 and holder.data[at - 1] & 0xC7 == 0x06 and holder.data[at - 2] in (
                    0x03, 0x2b, 0x33, 0x39, 0x3b, 0x81, 0x83, 0x89, 0x8b, 0x8c, 0x8e, 0xc4, 0xc5, 0xc7, 0xf7, 0xff):
                found.append((holder.name, at - 2))
            if at >= 1 and holder.data[at - 1] in (0xa1, 0xa3):
                found.append((holder.name, at - 1))
            at = holder.data.find(word, at + 1)
    return found


def _exclusive_selectors(oracle, home, dgroup, p, content, space, hull):
    """True when a CONST piece made only of far-data selector words must lie at `p` (2026-11-23).

    MSC keeps the segment of an external far object in a private CONST word that only its own file loads
    (`mov es,[D]`). The piece's content may repeat, so: every word of the piece is referenced only from inside
    this object's code, and is loaded there at least once; and every other CONST position holding the same content
    as relocated words has a word loaded by reached code outside this object, so it is another file's. Then the
    object's words can only be the ones at `p`."""
    from binding import reachable_from_entry
    relocated = {r["image_offset"] - dgroup for r in home.relocations}

    def loads(offset):
        return [(name, at) for name, at in _selector_references(oracle, home, offset)
                if oracle.spaces[name].data[at:at + 2] == b"\x8e\x06"]

    def inside(name, at):
        return name == space.name and hull[0] <= at and at + 4 <= hull[1]

    def reached(name, at):
        holder = oracle.spaces[name]
        for t in read_json_shared(ROOT / "evidence/targets.json")["functions"]:
            lo = (t["segment"] - holder.link_segment) * 16 + t["offset"]
            if t["space"] == name and t.get("boundary_status") == "REVIEWED" and lo <= at < lo + t["size"] and \
                    t.get("entry_kind", "direct-code") == "direct-code":
                if at in reachable_from_entry(oracle, f"{name}:{t['segment']:04x}:{t['offset']:04x}"):
                    return True
        return False

    length = len(content)
    words = range(0, length, 2)
    if p < CONST_START or length % 2 or any(p + k not in relocated for k in words):
        return False
    for k in words:
        if not all(inside(*ref) for ref in _selector_references(oracle, home, p + k)) or \
                not any(inside(*ref) for ref in loads(p + k)):
            return False
    for q in range(CONST_START, BSS_START - length + 1, 2):
        if q == p or any(q + k not in relocated for k in words) or \
                home.data[dgroup + q:dgroup + q + length] != content:
            continue
        if not any(not inside(*ref) and reached(*ref) for k in words for ref in loads(q + k)):
            return False
    return True


def _check_placements(module, placements, uses, binding, space, oracle, data_fixes=(), far_symbols=None,
                      data_symbols=None, hull=None, code=None):
    """Each placed DGROUP segment must be over-determined: initialized bytes equal the original
    DGROUP bytes at its placement, or (uninitialized) at least two distinct addends agree.
    Near-pointer fixups inside initialized data take their linked values (_linked_data)."""
    if not placements:
        return {}
    # Overlay code runs with the same DS (the startup DGROUP load); it needs the grounded runtime
    # DGROUP paragraph, since its own space does not hold DGROUP.
    require(binding and "frame" in binding and (space.name == "root" or "dgroup_segment" in binding),
            "Placed data needs the DGROUP frame (and dgroup_segment for overlay owners)")
    # The runtime DGROUP paragraph (the C runtime reloads DS with it before main) is
    # grounded by an original relocated word storing it; initialized DGROUP bytes live in
    # whichever space contains that paragraph (the preloaded overlay 17 in this image).
    home, dgroup = _dgroup_home(binding, space, oracle)
    report = {}
    for seg in module.segment_defs:
        if seg["name"] not in placements:
            continue
        p = placements[seg["name"]]
        require(type(p) is int and 0 <= p and p + seg["length"] <= 0x10000, "Placement outside DGROUP")
        content = module.segments.get(seg["name"])
        initialized = module.initialized_ranges.get(seg["name"], [])
        fields = [f for f in data_fixes if f["segment"] == seg["name"]]
        require(initialized or not fields, f"Fixups in uninitialized placed segment {seg['name']}")
        relocated = []
        if fields:
            content, relocated = _linked_data(seg["name"], content, fields, placements, far_symbols, data_symbols,
                                              code)
        if initialized:
            require("dgroup_segment" in binding,
                    "Initialized placed data needs the grounded runtime DGROUP paragraph (dgroup_segment)")
            require(_initialized_with_alignment_holes(initialized, seg["length"]),
                    f"Placed segment {seg['name']} must be completely initialized")
            start = dgroup + p
            require(start + seg["length"] <= home.size and home.data[start:start + seg["length"]] == content,
                    f"Placed segment {seg['name']} content differs from the original DGROUP bytes")
            # Original MZ relocations inside the segment: exactly the far pointers' segment words.
            inside = {r["image_offset"] - start for r in home.relocations
                      if start - 1 <= r["image_offset"] < start + seg["length"]}
            require(inside == set(relocated), f"Placed segment {seg['name']} overlaps original relocated words")
            # Content found once in the whole DGROUP image fixes P independently of any one field;
            # repeated content (zero words, short constants) fixes nothing, so each field then needs
            # its own support (_placed_support), like an unwitnessed v4 address.
            unique = seg["length"] >= 2 and _occurs_once(home, dgroup, content)  # one byte fixes nothing
            exclusive = (not unique and seg["name"] == "CONST" and hull is not None and
                         sorted(relocated) == list(range(0, seg["length"], 2)) and
                         _exclusive_selectors(oracle, home, dgroup, p, content, space, hull))
            bracketed = not unique and not exclusive and seg["name"] in binding.get("brackets", {})
            if bracketed:
                _bracketed(seg, p, binding["brackets"][seg["name"]], home, dgroup, binding["target_id"])
            unique = unique or exclusive or bracketed
            basis = (f"initialized content equals original {home.name}+{start:#x}" +
                     (", exclusive selector words" if exclusive else
                      ", bracketed by " + " and ".join(binding["brackets"][seg["name"]][k] for k in ("below", "above"))
                      if bracketed else
                      "" if unique else ", repeated content: per-field consensus"))
        else:
            # Uninitialized layout (array sizes, order) is chosen by the source, so distinct addends
            # never support each other; each field needs its own support (_placed_support).
            unique = False
            basis = "uninitialized: per-field consensus"
        report[seg["name"]] = {"placement": p, "length": seg["length"], "basis": basis, "unique": unique}
        if fields:
            report[seg["name"]]["pointer_fields"] = len(fields)
    require(set(report) == set(placements), "Placement for a segment the object does not declare")
    require(set(binding.get("brackets", {})) <= set(report) and
            all(", bracketed by " in report[n]["basis"] for n in binding.get("brackets", {})),
            "Unused or unsupported placement bracket")
    return report


def _bracketed(seg, p, bracket, home, dgroup, own_id):
    """Repeated (zero) initialized content whose place two neighbours leave no choice (docs/dgroup-binding.md "Brackets").

    Two other accepted groups place word-aligned contributions of the same segment whose bytes occur once in the
    original DGROUP image: one ends at P (or one alignment byte below), the other starts at P + length (or one byte
    above). A contiguous word-aligned contribution of that length has one place between them. That the segment lies in
    that gap is the claims' own doing: `_bracket_located` keeps the ordinary per-field proof for two of its offsets."""
    from binding import fits_once
    require(set(bracket) == {"below", "above"} and own_id not in bracket.values() and
            bracket["below"] != bracket["above"], "A placement bracket names two other groups")
    require(seg["alignment"] == 2 and seg["combine"] == 2 and p % 2 == 0,
            "A bracketed segment is word-aligned and public")
    edges = {}
    for side, group in bracket.items():
        found = [r for _, r in _accepted_recipes() if r.get("group_id") == group and r.get("binding")]
        require(len(found) == 1, f"Bracket {group} is not one accepted group")
        edges[side] = _unique_piece(found[0], seg["name"], home, dgroup)
    low, high = edges["below"][1], edges["above"][0]
    require(low <= p and p + seg["length"] <= high and fits_once(p, seg["length"], low, high, True),
            "Placement bracket leaves another position")


def _bracket_located(segments, states, reports):
    """A bracketed segment lies in its gap because two or more of its offsets are each addressed, equal to the
    original, at two or more distinct instruction starts of exact claims (the ordinary `_placed_support` proof)."""
    exact = {r["public"] for r in reports if r.get("exact")}
    for name in segments:
        sites = {}
        for public, state in states.items():
            for field in state["placed"] if public in exact else ():
                if field["key"][0] == name and field["equal"]:
                    sites.setdefault(field["key"], set()).add(field["insn"])
        require(sum(len(v) >= 2 for v in sites.values()) >= 2,
                f"Bracketed segment {name} is not located by two offsets with two equal sites each")


def _unique_piece(recipe, name, home, dgroup):
    """[lo, hi) of an accepted group's placed segment whose original bytes occur once in DGROUP. Validation compares
    the freshly compiled segment with those bytes and requires content, not a bracket, to fix its placement."""
    import json
    from common import project_path
    raw = project_path(recipe["binding"]).read_bytes()
    require(sha(raw) == recipe["binding_sha256"], "Bracket binding changed without acceptance")
    binding = json.loads(raw)
    require(name in binding.get("placements", {}) and name not in binding.get("brackets", {}),
            "Bracket group does not place that segment by its own content")
    lo = binding["placements"][name]
    length = next(d["length"] for d in binding["declarations"]["segments"] if d["name"] == name)
    content = home.data[dgroup + lo:dgroup + lo + length]
    require(length >= 2 and len(content) == length and _occurs_once(home, dgroup, content),
            "Bracket content occurs more than once")
    return lo, lo + length


